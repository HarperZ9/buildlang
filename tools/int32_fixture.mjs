// Writes tests/int32/js_rules.bld and tests/int32/js_rules.expected from one
// list of inputs: the Low Water hashStr (32-bit xor and Math.imul), JS ToInt32
// and ToUint32 on doubles, and the trace format's zero-divisor rules.
// Run: node tools/int32_fixture.mjs
import { writeFileSync } from 'node:fs';
function hashStr(s, seed = 0x9e3779b9) {
  let h = seed >>> 0;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  h ^= h >>> 16; h = Math.imul(h, 0x85ebca6b) >>> 0; h ^= h >>> 13; h = Math.imul(h, 0xc2b2ae35) >>> 0; h ^= h >>> 16;
  return h >>> 0;
}
const strings = ['', 'a', 'abc', 'lw-trace/1', '{"t":"cbegin","v":1}', 'seed#0', 'Lamb', 'x'.repeat(200), '0123456789'];
const seeds = [0, 1, 0x9e3779b9, 0xffffffff, 2026, 40];
const doubles = [0, -0, 1.9, -1.9, 2147483647, 2147483648, -2147483649, 4294967295, 4294967296, 4294967297.5,
  -4294967297.5, 1e20, -1e20, 9007199254740993, 1.7976931348623157e308, 5e-324, NaN, Infinity, -Infinity, 123456.789];
const pairs = [[5.5, 2], [-5.5, 2], [5.5, 0], [-5.5, -0], [0, 0], [1e300, 3], [7, 0.5], [-0, 3]];
const dv = new DataView(new ArrayBuffer(8));
const hex = (x) => { dv.setFloat64(0, x); return dv.getBigUint64(0).toString(16).padStart(16, '0'); };
const lit = (x) => `f64::from_bits(0x${hex(x)}_u64)`;
const quote = (s) => JSON.stringify(s);
const fmod0 = (a, b) => (b === 0 ? 0 : a % b);
const div0 = (a, b) => (b === 0 ? 0 : a / b);
const src = [
  '// Generated by tools/int32_fixture.mjs. Do not edit; rerun the script.',
  'fn hash_str(s: str, seed: u32) -> u32 {',
  '    let mut h: u32 = seed;',
  '    let bytes = s.as_bytes();',
  '    let mut i: usize = 0;',
  '    while i < s.len() {',
  '        h = h ^ (bytes[i] as u32);',
  '        h = h.wrapping_mul(0x01000193_u32);',
  '        i = i + 1;',
  '    }',
  '    h = h ^ (h >> 16);',
  '    h = h.wrapping_mul(0x85ebca6b_u32);',
  '    h = h ^ (h >> 13);',
  '    h = h.wrapping_mul(0xc2b2ae35_u32);',
  '    h ^ (h >> 16)',
  '}',
  '',
  'fn main() ~ Console {',
];
const want = [];
for (const s of strings) for (const seed of seeds) {
  src.push(`    println!("{}", hash_str(${quote(s)}, ${seed}_u32));`);
  want.push(String(hashStr(s, seed)));
}
for (const x of doubles) {
  src.push(`    println!("{} {}", ${lit(x)}.to_int32(), ${lit(x)}.to_uint32());`);
  want.push(`${x | 0} ${x >>> 0}`);
}
for (const [a, b] of pairs) {
  src.push(`    println!("{:016x} {:016x}", ${lit(a)}.fmod_or_zero(${lit(b)}).to_bits(), ${lit(a)}.div_or_zero(${lit(b)}).to_bits());`);
  want.push(`${hex(fmod0(a, b))} ${hex(div0(a, b))}`);
}
src.push('    let a: i32 = 2000000000;', '    let b: i32 = -5;', '    println!("{} {}", a.wrapping_mul(3), b ^ 12345);', '}');
want.push(`${Math.imul(2000000000, 3)} ${-5 ^ 12345}`);
writeFileSync('tests/int32/js_rules.bld', src.join('\n') + '\n');
writeFileSync('tests/int32/js_rules.expected', want.join('\n') + '\n');
