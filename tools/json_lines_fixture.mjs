// Writes tests/json/lines.bld and tests/json/lines.expected from one list of
// records shaped like Low Water's lw-trace/1 combat records: "t" first, the
// other keys in a fixed order, nested objects with sorted keys, no spaces.
// JS builds each record as an object in that key order and writes it with
// JSON.stringify; the BuildLang program builds the same line with json_obj,
// json_obj_sorted, json_arr, json_quote and to_json. Run: node tools/json_lines_fixture.mjs
import { writeFileSync } from 'node:fs';

const dv = new DataView(new ArrayBuffer(8));
const bits = (x) => { dv.setFloat64(0, x); return dv.getBigUint64(0).toString(16).padStart(16, '0'); };
// A value is a number, a string, or a node: {obj: [[k, v]...], sorted} or {arr: [v...]}.
const num = (x) => ({ num: x });
const obj = (pairs) => ({ obj: pairs, sorted: false });
const sobj = (pairs) => ({ obj: pairs, sorted: true });
const arr = (items) => ({ arr: items });

const toJs = (v) => {
  if (typeof v === 'string') return v;
  if ('num' in v) return v.num;
  if ('arr' in v) return v.arr.map(toJs);
  const pairs = v.sorted ? [...v.obj].sort((a, b) => (a[0] < b[0] ? -1 : a[0] > b[0] ? 1 : 0)) : v.obj;
  return Object.fromEntries(pairs.map(([k, x]) => [k, toJs(x)]));
};

let tmp = 0;
// Emits BuildLang statements that build the JSON text of v; returns the expression holding it.
const toBld = (v, out) => {
  if (typeof v === 'string') return `json_quote(${JSON.stringify(v)})`;
  if ('num' in v) return `f64::from_bits(0x${bits(v.num)}_u64).to_json()`;
  const name = `v${tmp++}`;
  if ('arr' in v) {
    out.push(`    let mut ${name}: Vec<str> = Vec::new();`);
    for (const item of v.arr) { const e = toBld(item, out); out.push(`    ${name}.push(${e});`); }
    const text = `t${tmp++}`;
    out.push(`    let ${text} = json_arr(${name});`);
    return text;
  }
  out.push(`    let mut ${name}k: Vec<str> = Vec::new();`, `    let mut ${name}v: Vec<str> = Vec::new();`);
  for (const [k, x] of v.obj) {
    const e = toBld(x, out);
    out.push(`    ${name}k.push(${JSON.stringify(k)});`, `    ${name}v.push(${e});`);
  }
  const text = `t${tmp++}`;
  out.push(`    let ${text} = ${v.sorted ? 'json_obj_sorted' : 'json_obj'}(${name}k, ${name}v);`);
  return text;
};

const fighter = (id, team, kind, x, z, face) =>
  sobj([['team', num(team)], ['id', num(id)], ['kind', kind], ['x', num(x)], ['z', num(z)], ['face', num(face)]]);
const records = [
  obj([['t', 'cbegin'], ['s', 'h'], ['v', num(1)], ['seed', num(7)], ['arena', 'yard "east"'],
    ['fighters', arr([fighter(1, 0, 'lamb', 0.5, -2, 0), fighter(2, 1, 'hound', 3.25, 1e-7, Math.PI)])]]),
  obj([['t', 'cin'], ['s', 'h'], ['tick', num(12)], ['lamb', sobj([['press', 'heavy'], ['mx', num(-0)], ['mz', num(0.1 + 0.2)], ['hold', 'guard']])]]),
  obj([['t', 'cev'], ['s', 'h'], ['tick', num(13)], ['n', 'hit'], ['d', sobj([['to', num(2)], ['dmg', num(12.5)], ['by', num(1)], ['at', arr([num(1e21), num(-1.5e-7), num(NaN)])]])]]),
  obj([['t', 'cstate'], ['s', 'h'], ['tick', num(60)], ['hash', num(3855992735)],
    ['f', arr([arr([num(1), num(0.5), num(-2), num(100), num(0)]), arr([num(2), num(3.25), num(1e-7), num(87.5), num(Infinity)])])]]),
  obj([['t', 'cend'], ['s', 'h'], ['tick', num(900)], ['outcome', 'win'], ['reason', 'line\nbreak\ttab\\slash'], ['hash', num(123456789)]]),
];

const src = ['// Generated by tools/json_lines_fixture.mjs. Do not edit; rerun the script.', 'mod json;', '', 'fn main() ~ Console {'];
const want = [];
for (const r of records) {
  const e = toBld(r, src);
  src.push(`    println!("{}", ${e});`);
  want.push(JSON.stringify(toJs(r)));
}
src.push('}');
writeFileSync('tests/json/lines.bld', src.join('\n') + '\n');
writeFileSync('tests/json/lines.expected', want.join('\n') + '\n');
