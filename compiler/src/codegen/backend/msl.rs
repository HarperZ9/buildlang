//! Apple Metal Shading Language (MSL) code generation backend.
//!
//! Emits `.metal` source from BuildLang MIR for Apple Silicon / macOS / iOS GPUs:
//! - Compute kernels (`kernel void`) with `[[buffer(N)]]` and thread/workgroup built-ins
//! - `threadgroup` workgroup-shared arrays and `threadgroup_barrier(mem_flags::mem_threadgroup)`
//! - Structured control flow reconstructed from dominator/post-dominator CFG analysis
//! - Fail-closed refusal of unsupported host/dynamic constructs (never silent stubs).

use std::collections::HashSet;

use super::{Backend, CodegenError, CodegenResult, Target};
use crate::codegen::analysis::structured_cfg::{self, HeaderKind, StructuredCfg};
use crate::codegen::ir::*;
use crate::codegen::{GeneratedCode, OutputFormat};

/// Apple Metal Shading Language backend.
pub struct MslBackend {
    output: String,
    indent: usize,
}

impl MslBackend {
    pub fn new() -> Self {
        Self {
            output: String::new(),
            indent: 0,
        }
    }

    fn writeln(&mut self, line: &str) {
        for _ in 0..self.indent {
            self.output.push_str("    ");
        }
        self.output.push_str(line);
        self.output.push('\n');
    }

    /// Generate MSL source text from a MIR module.
    pub fn generate_source(&mut self, module: &MirModule) -> CodegenResult<String> {
        self.output.clear();
        self.indent = 0;

        self.output.push_str("// Generated by BuildLang Compiler\n");
        self.output
            .push_str("// Target: Apple Metal Shading Language (MSL)\n");
        self.output.push_str("#include <metal_stdlib>\n");
        self.output.push_str("using namespace metal;\n\n");

        if !module.uniforms.is_empty() {
            self.writeln("struct _BuildLangUniforms {");
            self.indent += 1;
            for u in &module.uniforms {
                let ty = self.type_to_msl(&u.ty)?;
                self.writeln(&format!("{ty} {};", u.name));
            }
            self.indent -= 1;
            self.writeln("};\n");
        }

        for ty in &module.types {
            self.generate_struct(ty)?;
        }

        let mut emitted_any = false;
        for func in &module.functions {
            if func.is_declaration() {
                continue;
            }
            if func.name.as_ref() == "main" && func.shader_stage.is_none() {
                continue;
            }
            self.generate_function(func)?;
            emitted_any = true;
        }

        if !emitted_any && module.functions.iter().any(|f| !f.is_declaration()) {
            return Err(CodegenError::Unsupported(
                "MSL target requires at least one shader or GPU helper function (non-shader `fn main` cannot be lowered to Metal)".to_string(),
            ));
        }

        Ok(self.output.clone())
    }

    fn generate_struct(&mut self, ty: &MirTypeDef) -> CodegenResult<()> {
        match ty.name.as_ref() {
            "build_vec2" | "build_vec3" | "build_vec4" | "build_mat4" => return Ok(()),
            _ => {}
        }
        match &ty.kind {
            TypeDefKind::Struct { fields, .. } => {
                self.writeln(&format!("struct {} {{", ty.name));
                self.indent += 1;
                for (i, (name, field_ty)) in fields.iter().enumerate() {
                    let fname = name
                        .as_ref()
                        .map(|n| n.to_string())
                        .unwrap_or_else(|| format!("field_{i}"));
                    let msl_ty = self.type_to_msl(field_ty)?;
                    self.writeln(&format!("{msl_ty} {fname};"));
                }
                self.indent -= 1;
                self.writeln("};\n");
                Ok(())
            }
            TypeDefKind::Enum { .. } | TypeDefKind::Union { .. } => Err(CodegenError::Unsupported(
                format!("enum/union type `{}` is not supported in MSL", ty.name),
            )),
        }
    }

    fn generate_function(&mut self, func: &MirFunction) -> CodegenResult<()> {
        let is_compute = matches!(func.shader_stage, Some(ShaderStage::Compute));
        let written_params = Self::find_written_buffer_params(func);
        let needs_gid = Self::reads_nullary(func, |op| matches!(op, NullaryOp::ThreadIndex(_)));
        let needs_lid =
            Self::reads_nullary(func, |op| matches!(op, NullaryOp::LocalInvocationId(_)));
        let needs_wid = Self::reads_nullary(func, |op| matches!(op, NullaryOp::WorkgroupId(_)));

        if is_compute {
            let wg = Self::resolve_workgroup_size(func);
            self.writeln(&format!(
                "// workgroup_size: [{}, {}, {}]",
                wg[0], wg[1], wg[2]
            ));
        }

        let mut params = Vec::new();
        let mut buffer_slot: u32 = 0;
        let param_locals: Vec<&MirLocal> = func.locals.iter().filter(|l| l.is_param).collect();

        for (idx, param_ty) in func.sig.params.iter().enumerate() {
            let local = param_locals.get(idx).copied();
            let pname = local
                .map(|l| self.local_name(l.id, &func.locals))
                .unwrap_or_else(|| format!("p{idx}"));
            let is_writable = local.is_some_and(|l| l.is_mut || written_params.contains(&l.id));

            if is_compute {
                if let Some(elem_ty) = Self::buffer_elem_type(param_ty) {
                    let elem_msl = self.type_to_msl(elem_ty)?;
                    let qual = if is_writable {
                        "device"
                    } else {
                        "const device"
                    };
                    params.push(format!(
                        "{qual} {elem_msl}* {pname} [[buffer({buffer_slot})]]"
                    ));
                    buffer_slot += 1;
                } else {
                    let msl_ty = self.type_to_msl(param_ty)?;
                    params.push(format!(
                        "constant {msl_ty}& {pname} [[buffer({buffer_slot})]]"
                    ));
                    buffer_slot += 1;
                }
            } else {
                let msl_ty = self.type_to_msl(param_ty)?;
                params.push(format!("{msl_ty} {pname}"));
            }
        }

        if is_compute {
            if needs_gid {
                params.push("uint3 _bl_gid [[thread_position_in_grid]]".to_string());
            }
            if needs_lid {
                params.push("uint3 _bl_lid [[thread_position_in_threadgroup]]".to_string());
            }
            if needs_wid {
                params.push("uint3 _bl_wid [[threadgroup_position_in_grid]]".to_string());
            }
            self.writeln(&format!(
                "kernel void {}({}) {{",
                func.name,
                params.join(", ")
            ));
        } else {
            let ret_ty = self.type_to_msl(&func.sig.ret)?;
            self.writeln(&format!("{ret_ty} {}({}) {{", func.name, params.join(", ")));
        }

        self.indent += 1;
        let wg_arrays = self.emit_local_decls(func)?;

        if let Some(blocks) = &func.blocks {
            let cfg = structured_cfg::analyze(blocks);
            let mut visited = HashSet::new();
            if let Some(entry) = blocks.first() {
                self.emit_region(entry.id, None, blocks, func, &cfg, &wg_arrays, &mut visited)?;
            }
        }

        self.indent -= 1;
        self.writeln("}\n");
        Ok(())
    }

    fn emit_local_decls(&mut self, func: &MirFunction) -> CodegenResult<HashSet<LocalId>> {
        let mut wg_arrays = HashSet::new();
        for local in &func.locals {
            if local.is_param || matches!(local.ty, MirType::Void) {
                continue;
            }
            let name = self.local_name(local.id, &func.locals);
            if let Some(count) = Self::workgroup_array_len(local) {
                let elem_ty = match &local.ty {
                    MirType::Array(inner, _) | MirType::Slice(inner) => inner.as_ref(),
                    MirType::Ptr(inner) => match inner.as_ref() {
                        MirType::Array(e, _) | MirType::Slice(e) => e.as_ref(),
                        other => other,
                    },
                    other => other,
                };
                let elem_msl = self.type_to_msl(elem_ty)?;
                self.writeln(&format!("threadgroup {elem_msl} {name}[{count}];"));
                wg_arrays.insert(local.id);
                continue;
            }
            let ty_str = self.type_to_msl(&local.ty)?;
            self.writeln(&format!("{ty_str} {name};"));
        }
        Ok(wg_arrays)
    }

    #[allow(clippy::too_many_arguments)]
    fn emit_region(
        &mut self,
        start: BlockId,
        stop_at: Option<BlockId>,
        blocks: &[MirBlock],
        func: &MirFunction,
        cfg: &StructuredCfg,
        wg_arrays: &HashSet<LocalId>,
        visited: &mut HashSet<BlockId>,
    ) -> CodegenResult<()> {
        let mut current = Some(start);
        while let Some(bid) = current {
            if stop_at == Some(bid) || !visited.insert(bid) {
                break;
            }
            let Some(block) = blocks.iter().find(|b| b.id == bid) else {
                break;
            };

            match cfg.header(bid) {
                Some(HeaderKind::Loop { merge, .. }) => {
                    let Some(MirTerminator::If {
                        cond,
                        then_block,
                        else_block,
                    }) = &block.terminator
                    else {
                        return Err(CodegenError::InvalidMir(
                            "loop header missing If terminator".to_string(),
                        ));
                    };
                    self.writeln("while (true) {");
                    self.indent += 1;
                    self.emit_block_stmts(block, func, wg_arrays)?;
                    let cond_s = self.value_to_msl(cond, &func.locals)?;
                    let (body_block, exit_block, negate) = if *else_block == merge {
                        (*then_block, *else_block, true)
                    } else {
                        (*else_block, *then_block, false)
                    };
                    if negate {
                        self.writeln(&format!("if (!({cond_s})) {{ break; }}"));
                    } else {
                        self.writeln(&format!("if ({cond_s}) {{ break; }}"));
                    }
                    self.emit_region(body_block, Some(bid), blocks, func, cfg, wg_arrays, visited)?;
                    self.indent -= 1;
                    self.writeln("}");
                    current = Some(exit_block);
                }
                Some(HeaderKind::Selection { merge }) => {
                    self.emit_block_stmts(block, func, wg_arrays)?;
                    let Some(MirTerminator::If {
                        cond,
                        then_block,
                        else_block,
                    }) = &block.terminator
                    else {
                        return Err(CodegenError::InvalidMir(
                            "selection header missing If terminator".to_string(),
                        ));
                    };
                    let cond_s = self.value_to_msl(cond, &func.locals)?;
                    self.writeln(&format!("if ({cond_s}) {{"));
                    self.indent += 1;
                    self.emit_region(
                        *then_block,
                        Some(merge),
                        blocks,
                        func,
                        cfg,
                        wg_arrays,
                        visited,
                    )?;
                    self.indent -= 1;
                    if *else_block != merge && !Self::is_empty_goto(*else_block, merge, blocks) {
                        self.writeln("} else {");
                        self.indent += 1;
                        self.emit_region(
                            *else_block,
                            Some(merge),
                            blocks,
                            func,
                            cfg,
                            wg_arrays,
                            visited,
                        )?;
                        self.indent -= 1;
                    }
                    self.writeln("}");
                    current = Some(merge);
                }
                None => {
                    self.emit_block_stmts(block, func, wg_arrays)?;
                    current = self.emit_plain_terminator(&block.terminator, func, stop_at)?;
                }
            }
        }
        Ok(())
    }

    fn emit_block_stmts(
        &mut self,
        block: &MirBlock,
        func: &MirFunction,
        wg_arrays: &HashSet<LocalId>,
    ) -> CodegenResult<()> {
        for stmt in &block.stmts {
            match &stmt.kind {
                MirStmtKind::Assign { dest, value } => {
                    if wg_arrays.contains(dest) {
                        continue;
                    }
                    let dest_ty = func.locals.iter().find(|l| l.id == *dest).map(|l| &l.ty);
                    if matches!(dest_ty, Some(MirType::Void)) {
                        continue;
                    }
                    let lhs = self.local_name(*dest, &func.locals);
                    let rhs = match value {
                        MirRValue::Use(v) => self.value_to_msl_typed(v, dest_ty, &func.locals)?,
                        _ => self.rvalue_to_msl(value, func)?,
                    };
                    self.writeln(&format!("{lhs} = {rhs};"));
                }
                MirStmtKind::IndexStore {
                    base, index, value, ..
                } => {
                    let b = self.value_to_msl(base, &func.locals)?;
                    let idx = self.value_to_msl(index, &func.locals)?;
                    let val = self.rvalue_to_msl(value, func)?;
                    self.writeln(&format!("{b}[{idx}] = {val};"));
                }
                MirStmtKind::FieldAssign {
                    base,
                    field_name,
                    value,
                } => {
                    let b = self.local_name(*base, &func.locals);
                    let val = self.rvalue_to_msl(value, func)?;
                    self.writeln(&format!("{b}.{field_name} = {val};"));
                }
                MirStmtKind::WorkgroupBarrier => {
                    self.writeln("threadgroup_barrier(mem_flags::mem_threadgroup);");
                }
                MirStmtKind::StorageLive(_) | MirStmtKind::StorageDead(_) | MirStmtKind::Nop => {}
                MirStmtKind::GlobalStore { name, .. } => {
                    return Err(CodegenError::Unsupported(format!(
                        "mutable module global `{name}` store is not supported in MSL"
                    )));
                }
                MirStmtKind::DerefAssign { .. } | MirStmtKind::FieldDerefAssign { .. } => {
                    return Err(CodegenError::Unsupported(
                        "raw pointer dereference assignment is not supported in MSL".to_string(),
                    ));
                }
            }
        }
        Ok(())
    }

    fn emit_plain_terminator(
        &mut self,
        term: &Option<MirTerminator>,
        func: &MirFunction,
        stop_at: Option<BlockId>,
    ) -> CodegenResult<Option<BlockId>> {
        match term {
            None => Ok(None),
            Some(MirTerminator::Goto(target)) => {
                if stop_at == Some(*target) {
                    Ok(None)
                } else {
                    Ok(Some(*target))
                }
            }
            Some(MirTerminator::Return(Some(val))) => {
                if matches!(func.shader_stage, Some(ShaderStage::Compute)) {
                    self.writeln("return;");
                } else {
                    let v = self.value_to_msl(val, &func.locals)?;
                    self.writeln(&format!("return {v};"));
                }
                Ok(None)
            }
            Some(MirTerminator::Return(None)) => {
                self.writeln("return;");
                Ok(None)
            }
            Some(MirTerminator::Call {
                func: callee,
                args,
                dest,
                target,
                ..
            }) => {
                let expr = self.call_expr_to_msl(callee, args, &func.locals)?;
                if let Some(d) = dest {
                    let lhs = self.local_name(*d, &func.locals);
                    self.writeln(&format!("{lhs} = {expr};"));
                } else {
                    self.writeln(&format!("{expr};"));
                }
                Ok(target.filter(|t| stop_at != Some(*t)))
            }
            Some(MirTerminator::If {
                cond,
                then_block,
                else_block,
            }) => {
                let c = self.value_to_msl(cond, &func.locals)?;
                self.writeln(&format!("if ({c}) {{ /* unstructured branch */ }}"));
                let _ = (then_block, else_block);
                Err(CodegenError::Unsupported(
                    "unstructured control flow is not supported in MSL".to_string(),
                ))
            }
            Some(MirTerminator::Switch { .. }) => Err(CodegenError::Unsupported(
                "switch terminator is not yet supported in MSL".to_string(),
            )),
            Some(MirTerminator::Unreachable) => {
                self.writeln("return;");
                Ok(None)
            }
            Some(MirTerminator::Drop { target, .. }) => Ok(Some(*target)),
            Some(MirTerminator::Assert { target, .. }) => Ok(Some(*target)),
            Some(MirTerminator::Resume | MirTerminator::Abort) => Err(CodegenError::Unsupported(
                "abort/unwind is not supported in MSL shaders".to_string(),
            )),
        }
    }

    fn rvalue_to_msl(&self, rv: &MirRValue, func: &MirFunction) -> CodegenResult<String> {
        match rv {
            MirRValue::Use(v) => self.value_to_msl(v, &func.locals),
            MirRValue::BinaryOp { op, left, right } => {
                let l_ty = Self::value_type(left, &func.locals);
                let r_ty = Self::value_type(right, &func.locals);
                let l_expected = r_ty.as_ref().filter(|t| matches!(t, MirType::Int(_, _)));
                let r_expected = l_ty.as_ref().filter(|t| matches!(t, MirType::Int(_, _)));
                let l = self.value_to_msl_typed(left, l_expected, &func.locals)?;
                let r = self.value_to_msl_typed(right, r_expected, &func.locals)?;
                let sym = match op {
                    BinOp::Add | BinOp::AddChecked | BinOp::AddWrapping | BinOp::AddSaturating => {
                        "+"
                    }
                    BinOp::Sub | BinOp::SubChecked | BinOp::SubWrapping | BinOp::SubSaturating => {
                        "-"
                    }
                    BinOp::Mul | BinOp::MulChecked | BinOp::MulWrapping | BinOp::MulSaturating => {
                        "*"
                    }
                    BinOp::Div => "/",
                    BinOp::Rem => "%",
                    BinOp::Eq => "==",
                    BinOp::Ne => "!=",
                    BinOp::Lt => "<",
                    BinOp::Le => "<=",
                    BinOp::Gt => ">",
                    BinOp::Ge => ">=",
                    BinOp::BitAnd => "&",
                    BinOp::BitOr => "|",
                    BinOp::BitXor => "^",
                    BinOp::Shl => "<<",
                    BinOp::Shr => ">>",
                    BinOp::Pow => return Ok(format!("pow({l}, {r})")),
                };
                Ok(format!("({l} {sym} {r})"))
            }
            MirRValue::UnaryOp { op, operand } => {
                let v = self.value_to_msl(operand, &func.locals)?;
                Ok(match op {
                    UnaryOp::Neg => format!("(-{v})"),
                    UnaryOp::Not => format!("(!{v})"),
                    UnaryOp::BitNot => format!("(~{v})"),
                })
            }
            MirRValue::Cast { value, ty, .. } => {
                let v = self.value_to_msl(value, &func.locals)?;
                let t = self.type_to_msl(ty)?;
                Ok(format!("static_cast<{t}>({v})"))
            }
            MirRValue::FieldAccess {
                base, field_name, ..
            } => {
                let b = self.value_to_msl(base, &func.locals)?;
                Ok(format!("{b}.{field_name}"))
            }
            MirRValue::IndexAccess { base, index, .. } => {
                let b = self.value_to_msl(base, &func.locals)?;
                let i = self.value_to_msl(index, &func.locals)?;
                Ok(format!("{b}[{i}]"))
            }
            MirRValue::Aggregate { kind, operands } => {
                let mut ops = Vec::with_capacity(operands.len());
                for o in operands {
                    ops.push(self.value_to_msl(o, &func.locals)?);
                }
                match kind {
                    AggregateKind::Struct(name) => {
                        let ctor = match name.as_ref() {
                            "build_vec2" => "float2",
                            "build_vec3" => "float3",
                            "build_vec4" => "float4",
                            other => other,
                        };
                        Ok(format!("{ctor}({})", ops.join(", ")))
                    }
                    AggregateKind::Array(_) => Ok(format!("{{{}}}", ops.join(", "))),
                    _ => Err(CodegenError::Unsupported(format!(
                        "aggregate kind `{kind:?}` is not supported in MSL"
                    ))),
                }
            }
            MirRValue::NullaryOp(op, ty) => match op {
                NullaryOp::ThreadIndex(0) => Ok("_bl_gid.x".to_string()),
                NullaryOp::ThreadIndex(1) => Ok("_bl_gid.y".to_string()),
                NullaryOp::ThreadIndex(2) => Ok("_bl_gid.z".to_string()),
                NullaryOp::LocalInvocationId(0) => Ok("_bl_lid.x".to_string()),
                NullaryOp::LocalInvocationId(1) => Ok("_bl_lid.y".to_string()),
                NullaryOp::LocalInvocationId(2) => Ok("_bl_lid.z".to_string()),
                NullaryOp::WorkgroupId(0) => Ok("_bl_wid.x".to_string()),
                NullaryOp::WorkgroupId(1) => Ok("_bl_wid.y".to_string()),
                NullaryOp::WorkgroupId(2) => Ok("_bl_wid.z".to_string()),
                NullaryOp::SizeOf => Ok(format!("sizeof({})", self.type_to_msl(ty)?)),
                NullaryOp::AlignOf => Ok(format!("alignof({})", self.type_to_msl(ty)?)),
                other => Err(CodegenError::Unsupported(format!(
                    "nullary op `{other:?}` is not supported in MSL"
                ))),
            },
            MirRValue::TextureSample {
                texture,
                sampler,
                coords,
            } => {
                let t = self.value_to_msl(texture, &func.locals)?;
                let s = self.value_to_msl(sampler, &func.locals)?;
                let uv = self.value_to_msl(coords, &func.locals)?;
                Ok(format!("{t}.sample({s}, {uv})"))
            }
            other => Err(CodegenError::Unsupported(format!(
                "rvalue `{other:?}` is not supported in MSL"
            ))),
        }
    }

    fn call_expr_to_msl(
        &self,
        callee: &MirValue,
        args: &[MirValue],
        locals: &[MirLocal],
    ) -> CodegenResult<String> {
        let name = match callee {
            MirValue::Function(n) | MirValue::Global(n) => n.as_ref(),
            _ => {
                return Err(CodegenError::Unsupported(
                    "indirect function calls are not supported in MSL".to_string(),
                ));
            }
        };
        if matches!(
            name,
            "printf"
                | "puts"
                | "print"
                | "println"
                | "build_println_str"
                | "build_println_i64"
                | "build_println_f64"
                | "build_print_str"
        ) || name.starts_with("build_vec_")
            || name.starts_with("build_hmap_")
        {
            return Err(CodegenError::Unsupported(format!(
                "host runtime call `{name}` is not supported in MSL shaders"
            )));
        }

        let mapped = match name {
            "fabs" | "fabsf" => "abs",
            "sqrtf" => "sqrt",
            "sinf" => "sin",
            "cosf" => "cos",
            "tanf" => "tan",
            "expf" => "exp",
            "logf" => "log",
            "powf" => "pow",
            "floorf" => "floor",
            "ceilf" => "ceil",
            "fmaf" => "fma",
            "build_dot2" | "build_dot3" | "build_dot4" => "dot",
            "build_normalize2" | "build_normalize3" | "build_normalize4" => "normalize",
            "build_length2" | "build_length3" | "build_length4" => "length",
            "build_cross" => "cross",
            "build_reflect3" => "reflect",
            "build_mix" | "lerp" | "build_lerp2" | "build_lerp3" | "build_lerp4" => "mix",
            "build_clampf" | "build_clamp3" => "clamp",
            "build_smoothstep" => "smoothstep",
            "build_fract" => "fract",
            "build_step" => "step",
            "build_min_f32" | "build_min_i32" => "min",
            "build_max_f32" | "build_max_i32" => "max",
            "build_vec2_new" => "float2",
            "build_vec3_new" => "float3",
            "build_vec4_new" => "float4",
            other => other,
        };

        let mut arg_strs = Vec::with_capacity(args.len());
        for a in args {
            arg_strs.push(self.value_to_msl(a, locals)?);
        }
        Ok(format!("{mapped}({})", arg_strs.join(", ")))
    }

    fn value_to_msl(&self, value: &MirValue, locals: &[MirLocal]) -> CodegenResult<String> {
        match value {
            MirValue::Local(id) => Ok(self.local_name(*id, locals)),
            MirValue::Const(c) => self.const_to_msl(c),
            MirValue::Global(name) | MirValue::Function(name) => Ok(name.to_string()),
        }
    }

    fn value_type(value: &MirValue, locals: &[MirLocal]) -> Option<MirType> {
        match value {
            MirValue::Local(id) => locals.iter().find(|l| l.id == *id).map(|l| l.ty.clone()),
            _ => None,
        }
    }

    fn value_to_msl_typed(
        &self,
        value: &MirValue,
        expected: Option<&MirType>,
        locals: &[MirLocal],
    ) -> CodegenResult<String> {
        if let (MirValue::Const(MirConst::Int(v, _)), Some(MirType::Int(_, false))) =
            (value, expected)
        {
            if *v >= 0 {
                return Ok(format!("{v}u"));
            }
        }
        self.value_to_msl(value, locals)
    }

    fn is_empty_goto(bid: BlockId, target: BlockId, blocks: &[MirBlock]) -> bool {
        blocks.iter().find(|b| b.id == bid).is_some_and(|b| {
            b.stmts.is_empty() && b.terminator == Some(MirTerminator::Goto(target))
        })
    }

    fn const_to_msl(&self, c: &MirConst) -> CodegenResult<String> {
        match c {
            MirConst::Bool(b) => Ok(if *b { "true" } else { "false" }.to_string()),
            MirConst::Int(v, ty) => match ty {
                MirType::Int(_, false) if *v >= 0 => Ok(format!("{v}u")),
                _ => Ok(format!("{v}")),
            },
            MirConst::Uint(v, _) => Ok(format!("{v}u")),
            MirConst::Float(v, ty) => {
                if matches!(ty, MirType::Float(FloatSize::F64)) {
                    return Err(CodegenError::Unsupported(
                        "f64 literal is not supported in MSL (Apple Metal supports f32/half)"
                            .to_string(),
                    ));
                }
                let s = format!("{v}");
                if !s.contains('.') && !s.contains('e') && !s.contains('E') {
                    Ok(format!("{s}.0f"))
                } else {
                    Ok(format!("{s}f"))
                }
            }
            MirConst::Unit => Ok("0".to_string()),
            MirConst::Str(_) | MirConst::ByteStr(_) => Err(CodegenError::Unsupported(
                "string constants are not supported in MSL shaders".to_string(),
            )),
            other => Err(CodegenError::Unsupported(format!(
                "constant `{other:?}` is not supported in MSL"
            ))),
        }
    }

    fn type_to_msl(&self, ty: &MirType) -> CodegenResult<String> {
        match ty {
            MirType::Void => Ok("void".to_string()),
            MirType::Bool => Ok("bool".to_string()),
            MirType::Int(size, signed) => match (size, signed) {
                (IntSize::I8, true) => Ok("char".to_string()),
                (IntSize::I8, false) => Ok("uchar".to_string()),
                (IntSize::I16, true) => Ok("short".to_string()),
                (IntSize::I16, false) => Ok("ushort".to_string()),
                (IntSize::I32, true) => Ok("int".to_string()),
                (IntSize::I32, false) => Ok("uint".to_string()),
                (IntSize::I64 | IntSize::ISize, true) => Ok("long".to_string()),
                (IntSize::I64 | IntSize::ISize, false) => Ok("ulong".to_string()),
                (IntSize::I128, _) => Err(CodegenError::Unsupported(
                    "128-bit integer type is not supported in MSL".to_string(),
                )),
            },
            MirType::Float(FloatSize::F32) => Ok("float".to_string()),
            MirType::Float(FloatSize::F64) => Err(CodegenError::Unsupported(
                "f64 (double) type is not supported in Apple Metal Shading Language; use f32"
                    .to_string(),
            )),
            MirType::Struct(name) => Ok(match name.as_ref() {
                "build_vec2" => "float2".to_string(),
                "build_vec3" => "float3".to_string(),
                "build_vec4" => "float4".to_string(),
                "build_mat4" => "float4x4".to_string(),
                other => other.to_string(),
            }),
            MirType::Vector(elem, n) => Ok(format!("{}{}", self.type_to_msl(elem)?, n)),
            MirType::Array(elem, len) => Ok(format!("array<{}, {len}>", self.type_to_msl(elem)?)),
            MirType::Texture2D(elem) => Ok(format!("texture2d<{}>", self.type_to_msl(elem)?)),
            MirType::Sampler => Ok("sampler".to_string()),
            MirType::Ptr(inner) => {
                if let Some(elem) = Self::buffer_elem_type(inner) {
                    Ok(format!("device {}*", self.type_to_msl(elem)?))
                } else {
                    Ok(format!("device {}*", self.type_to_msl(inner)?))
                }
            }
            MirType::Slice(elem) => Ok(format!("device {}*", self.type_to_msl(elem)?)),
            MirType::Vec(_) | MirType::Map(_, _) | MirType::TraitObject(_) | MirType::FnPtr(_) => {
                Err(CodegenError::Unsupported(format!(
                    "dynamic/host type `{ty}` is not supported in MSL"
                )))
            }
            other => Err(CodegenError::Unsupported(format!(
                "type `{other}` is not supported in MSL"
            ))),
        }
    }

    fn buffer_elem_type(ty: &MirType) -> Option<&MirType> {
        match ty {
            MirType::Slice(elem) => Some(elem.as_ref()),
            MirType::Ptr(inner) => match inner.as_ref() {
                MirType::Slice(elem) | MirType::Array(elem, _) => Some(elem.as_ref()),
                _ => None,
            },
            _ => None,
        }
    }

    fn workgroup_array_len(local: &MirLocal) -> Option<u32> {
        local
            .annotations
            .iter()
            .find_map(|a| a.strip_prefix("Workgroup:")?.parse::<u32>().ok())
    }

    fn find_written_buffer_params(func: &MirFunction) -> HashSet<LocalId> {
        let mut out = HashSet::new();
        if let Some(blocks) = &func.blocks {
            for b in blocks {
                for s in &b.stmts {
                    if let MirStmtKind::IndexStore {
                        base: MirValue::Local(id),
                        ..
                    } = &s.kind
                    {
                        out.insert(*id);
                    }
                }
            }
        }
        out
    }

    fn reads_nullary(func: &MirFunction, pred: impl Fn(&NullaryOp) -> bool) -> bool {
        func.blocks.as_ref().is_some_and(|blocks| {
            blocks.iter().any(|b| {
                b.stmts.iter().any(|s| match &s.kind {
                    MirStmtKind::Assign {
                        value: MirRValue::NullaryOp(op, _),
                        ..
                    } => pred(op),
                    _ => false,
                })
            })
        })
    }

    fn resolve_workgroup_size(func: &MirFunction) -> [u32; 3] {
        if let Some(sz) = func.workgroup_size {
            return sz;
        }
        if Self::reads_nullary(
            func,
            |op| matches!(op, NullaryOp::ThreadIndex(c) if *c >= 1),
        ) {
            [16, 16, 1]
        } else {
            [64, 1, 1]
        }
    }

    fn local_name(&self, id: LocalId, locals: &[MirLocal]) -> String {
        locals
            .iter()
            .find(|l| l.id == id)
            .and_then(|l| l.name.as_ref())
            .map(|n| match n.as_ref() {
                "device" | "constant" | "thread" | "threadgroup" | "kernel" | "vertex"
                | "fragment" | "sampler" | "texture" | "half" => format!("_{n}"),
                "class" | "struct" | "union" | "enum" | "namespace" | "template" | "typename"
                | "using" | "private" | "public" | "protected" | "virtual" | "inline"
                | "static" | "extern" | "const" | "volatile" | "register" | "auto" | "signed"
                | "unsigned" | "char" | "short" | "long" | "int" | "uint" | "float" | "double"
                | "bool" | "void" | "default" | "switch" | "case" | "operator" | "new"
                | "delete" | "this" | "throw" | "try" | "catch" | "sizeof" | "alignof"
                | "restrict" | "metal" | "object" | "mesh" | "visible" | "stitchable" | "step"
                | "mix" | "clamp" | "fma" => format!("_bl_{n}"),
                other => other.to_string(),
            })
            .unwrap_or_else(|| format!("_{}", id.0))
    }
}

impl Default for MslBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl Backend for MslBackend {
    fn generate(&mut self, mir: &MirModule) -> CodegenResult<GeneratedCode> {
        let src = self.generate_source(mir)?;
        Ok(GeneratedCode::new(OutputFormat::Msl, src.into_bytes()))
    }

    fn target(&self) -> Target {
        Target::Msl
    }
}
