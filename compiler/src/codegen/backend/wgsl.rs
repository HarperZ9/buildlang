//! WebGPU Shading Language (WGSL) code generation backend.
//!
//! Emits `.wgsl` compute and helper shaders from BuildLang MIR:
//! - `@compute @workgroup_size(X, Y, Z)` entry points
//! - `@group(0) @binding(N)` storage buffers (`read` / `read_write`) and uniform blocks
//! - `var<workgroup>` shared arrays and `workgroupBarrier()`
//! - Structured control flow (`if`/`else`, `loop { ... if (!(cond)) { break; } ... }`)
//! - Fail-closed refusal of unsupported types/constructs (e.g., `f64`, `i64`, `Vec`, strings).

use std::collections::{HashMap, HashSet};

use super::{Backend, CodegenError, CodegenResult, Target};
use crate::codegen::analysis::structured_cfg::{self, HeaderKind, StructuredCfg};
use crate::codegen::ir::*;
use crate::codegen::{GeneratedCode, OutputFormat};

/// WebGPU Shading Language (WGSL) backend.
pub struct WgslBackend {
    output: String,
    indent: usize,
}

struct EntryBindings {
    buffer_vars: HashMap<LocalId, String>,
    scalar_fields: HashMap<LocalId, String>,
    uniform_var: Option<String>,
    workgroup_vars: HashMap<LocalId, String>,
}

impl WgslBackend {
    pub fn new() -> Self {
        Self {
            output: String::new(),
            indent: 0,
        }
    }

    fn writeln(&mut self, line: &str) {
        for _ in 0..self.indent {
            self.output.push_str("    ");
        }
        self.output.push_str(line);
        self.output.push('\n');
    }

    /// Generate WGSL source text from a MIR module.
    pub fn generate_source(&mut self, module: &MirModule) -> CodegenResult<String> {
        self.output.clear();
        self.indent = 0;

        self.output.push_str("// Generated by BuildLang Compiler\n");
        self.output
            .push_str("// Target: WebGPU Shading Language (WGSL)\n\n");

        if !module.uniforms.is_empty() {
            self.writeln("struct _BuildLangUniforms {");
            self.indent += 1;
            for u in &module.uniforms {
                let ty = self.type_to_wgsl(&u.ty)?;
                self.writeln(&format!("{}: {ty},", u.name));
            }
            self.indent -= 1;
            self.writeln("};\n");
        }

        for ty in &module.types {
            self.generate_struct(ty)?;
        }

        let compute_count = module
            .functions
            .iter()
            .filter(|f| !f.is_declaration() && matches!(f.shader_stage, Some(ShaderStage::Compute)))
            .count();

        let mut emitted_any = false;
        for func in &module.functions {
            if func.is_declaration() {
                continue;
            }
            if func.name.as_ref() == "main" && func.shader_stage.is_none() {
                continue;
            }
            self.generate_function(func, compute_count > 1)?;
            emitted_any = true;
        }

        if !emitted_any && module.functions.iter().any(|f| !f.is_declaration()) {
            return Err(CodegenError::Unsupported(
                "WGSL target requires at least one shader or GPU helper function (non-shader `fn main` cannot be lowered to WGSL)".to_string(),
            ));
        }

        Ok(self.output.clone())
    }

    fn generate_struct(&mut self, ty: &MirTypeDef) -> CodegenResult<()> {
        match ty.name.as_ref() {
            "build_vec2" | "build_vec3" | "build_vec4" | "build_mat4" => return Ok(()),
            _ => {}
        }
        match &ty.kind {
            TypeDefKind::Struct { fields, .. } => {
                self.writeln(&format!("struct {} {{", ty.name));
                self.indent += 1;
                for (i, (name, field_ty)) in fields.iter().enumerate() {
                    let fname = name
                        .as_ref()
                        .map(|n| n.to_string())
                        .unwrap_or_else(|| format!("field_{i}"));
                    let wgsl_ty = self.type_to_wgsl(field_ty)?;
                    self.writeln(&format!("{fname}: {wgsl_ty},"));
                }
                self.indent -= 1;
                self.writeln("};\n");
                Ok(())
            }
            TypeDefKind::Enum { .. } | TypeDefKind::Union { .. } => Err(CodegenError::Unsupported(
                format!("enum/union type `{}` is not supported in WGSL", ty.name),
            )),
        }
    }

    fn generate_function(
        &mut self,
        func: &MirFunction,
        prefix_bindings: bool,
    ) -> CodegenResult<()> {
        let is_compute = matches!(func.shader_stage, Some(ShaderStage::Compute));
        let bindings = if is_compute {
            self.emit_compute_module_bindings(func, prefix_bindings)?
        } else {
            EntryBindings {
                buffer_vars: HashMap::new(),
                scalar_fields: HashMap::new(),
                uniform_var: None,
                workgroup_vars: HashMap::new(),
            }
        };

        if is_compute {
            let wg = Self::resolve_workgroup_size(func);
            self.writeln(&format!(
                "@compute @workgroup_size({}, {}, {})",
                wg[0], wg[1], wg[2]
            ));
            let mut builtins = Vec::new();
            if Self::reads_nullary(func, |op| matches!(op, NullaryOp::ThreadIndex(_))) {
                builtins.push("@builtin(global_invocation_id) _bl_gid: vec3<u32>".to_string());
            }
            if Self::reads_nullary(func, |op| matches!(op, NullaryOp::LocalInvocationId(_))) {
                builtins.push("@builtin(local_invocation_id) _bl_lid: vec3<u32>".to_string());
            }
            if Self::reads_nullary(func, |op| matches!(op, NullaryOp::WorkgroupId(_))) {
                builtins.push("@builtin(workgroup_id) _bl_wid: vec3<u32>".to_string());
            }
            self.writeln(&format!("fn {}({}) {{", func.name, builtins.join(", ")));
        } else {
            let param_locals: Vec<&MirLocal> = func.locals.iter().filter(|l| l.is_param).collect();
            let mut params = Vec::new();
            for (i, ty) in func.sig.params.iter().enumerate() {
                let pname = param_locals
                    .get(i)
                    .map(|l| self.local_name(l.id, &func.locals))
                    .unwrap_or_else(|| format!("p{i}"));
                let wty = self.type_to_wgsl(ty)?;
                params.push(format!("{pname}: {wty}"));
            }
            if matches!(func.sig.ret, MirType::Void) {
                self.writeln(&format!("fn {}({}) {{", func.name, params.join(", ")));
            } else {
                let rty = self.type_to_wgsl(&func.sig.ret)?;
                self.writeln(&format!(
                    "fn {}({}) -> {rty} {{",
                    func.name,
                    params.join(", ")
                ));
            }
        }

        self.indent += 1;
        for local in &func.locals {
            if local.is_param
                || matches!(local.ty, MirType::Void)
                || bindings.workgroup_vars.contains_key(&local.id)
            {
                continue;
            }
            let name = self.local_name(local.id, &func.locals);
            let wty = self.type_to_wgsl(&local.ty)?;
            self.writeln(&format!("var {name}: {wty};"));
        }

        if let Some(blocks) = &func.blocks {
            let cfg = structured_cfg::analyze(blocks);
            let mut visited = HashSet::new();
            if let Some(entry) = blocks.first() {
                self.emit_region(entry.id, None, blocks, func, &cfg, &bindings, &mut visited)?;
            }
        }

        self.indent -= 1;
        self.writeln("}\n");
        Ok(())
    }

    fn emit_compute_module_bindings(
        &mut self,
        func: &MirFunction,
        prefix_bindings: bool,
    ) -> CodegenResult<EntryBindings> {
        let written = Self::find_written_buffer_params(func);
        let param_locals: Vec<&MirLocal> = func.locals.iter().filter(|l| l.is_param).collect();

        let mut buffer_vars = HashMap::new();
        let mut scalar_fields = HashMap::new();
        let mut scalar_decls: Vec<(String, String)> = Vec::new();
        let mut binding_idx: u32 = 0;

        for (idx, param_ty) in func.sig.params.iter().enumerate() {
            let local = param_locals.get(idx).copied();
            let raw_name = local
                .map(|l| self.local_name(l.id, &func.locals))
                .unwrap_or_else(|| format!("p{idx}"));
            let var_name = if prefix_bindings {
                format!("{}_{raw_name}", func.name)
            } else {
                raw_name.clone()
            };

            if let Some(elem_ty) = Self::buffer_elem_type(param_ty) {
                let elem_wgsl = self.type_to_wgsl(elem_ty)?;
                let is_writable = local.is_some_and(|l| l.is_mut || written.contains(&l.id));
                let access = if is_writable { "read_write" } else { "read" };
                self.writeln(&format!(
                    "@group(0) @binding({binding_idx}) var<storage, {access}> {var_name}: array<{elem_wgsl}>;"
                ));
                if let Some(l) = local {
                    buffer_vars.insert(l.id, var_name);
                }
                binding_idx += 1;
            } else {
                let wty = self.type_to_wgsl(param_ty)?;
                scalar_decls.push((raw_name.clone(), wty));
                if let Some(l) = local {
                    scalar_fields.insert(l.id, raw_name);
                }
            }
        }

        let uniform_var = if !scalar_decls.is_empty() {
            let struct_name = format!("_Params_{}", func.name);
            let uvar = format!("_params_{}", func.name);
            self.writeln(&format!("struct {struct_name} {{"));
            self.indent += 1;
            for (fname, fty) in &scalar_decls {
                self.writeln(&format!("{fname}: {fty},"));
            }
            self.indent -= 1;
            self.writeln("};");
            self.writeln(&format!(
                "@group(0) @binding({binding_idx}) var<uniform> {uvar}: {struct_name};"
            ));
            Some(uvar)
        } else {
            None
        };

        let mut workgroup_vars = HashMap::new();
        for local in &func.locals {
            if let Some(count) = Self::workgroup_array_len(local) {
                let elem_ty = match &local.ty {
                    MirType::Array(inner, _) | MirType::Slice(inner) => inner.as_ref(),
                    MirType::Ptr(inner) => match inner.as_ref() {
                        MirType::Array(e, _) | MirType::Slice(e) => e.as_ref(),
                        other => other,
                    },
                    other => other,
                };
                let elem_wgsl = self.type_to_wgsl(elem_ty)?;
                let raw = self.local_name(local.id, &func.locals);
                let wg_name = if prefix_bindings {
                    format!("{}_{raw}", func.name)
                } else {
                    raw
                };
                self.writeln(&format!(
                    "var<workgroup> {wg_name}: array<{elem_wgsl}, {count}>;"
                ));
                workgroup_vars.insert(local.id, wg_name);
            }
        }

        if !buffer_vars.is_empty() || uniform_var.is_some() || !workgroup_vars.is_empty() {
            self.output.push('\n');
        }

        Ok(EntryBindings {
            buffer_vars,
            scalar_fields,
            uniform_var,
            workgroup_vars,
        })
    }

    #[allow(clippy::too_many_arguments)]
    fn emit_region(
        &mut self,
        start: BlockId,
        stop_at: Option<BlockId>,
        blocks: &[MirBlock],
        func: &MirFunction,
        cfg: &StructuredCfg,
        bindings: &EntryBindings,
        visited: &mut HashSet<BlockId>,
    ) -> CodegenResult<()> {
        let mut current = Some(start);
        while let Some(bid) = current {
            if stop_at == Some(bid) || !visited.insert(bid) {
                break;
            }
            let Some(block) = blocks.iter().find(|b| b.id == bid) else {
                break;
            };

            match cfg.header(bid) {
                Some(HeaderKind::Loop { merge, .. }) => {
                    let Some(MirTerminator::If {
                        cond,
                        then_block,
                        else_block,
                    }) = &block.terminator
                    else {
                        return Err(CodegenError::InvalidMir(
                            "loop header missing If terminator".to_string(),
                        ));
                    };
                    self.writeln("loop {");
                    self.indent += 1;
                    self.emit_block_stmts(block, func, bindings)?;
                    let cond_s = self.value_to_wgsl(cond, &func.locals, bindings)?;
                    let (body_block, exit_block, negate) = if *else_block == merge {
                        (*then_block, *else_block, true)
                    } else {
                        (*else_block, *then_block, false)
                    };
                    if negate {
                        self.writeln(&format!("if (!({cond_s})) {{ break; }}"));
                    } else {
                        self.writeln(&format!("if ({cond_s}) {{ break; }}"));
                    }
                    self.emit_region(body_block, Some(bid), blocks, func, cfg, bindings, visited)?;
                    self.indent -= 1;
                    self.writeln("}");
                    current = Some(exit_block);
                }
                Some(HeaderKind::Selection { merge }) => {
                    self.emit_block_stmts(block, func, bindings)?;
                    let Some(MirTerminator::If {
                        cond,
                        then_block,
                        else_block,
                    }) = &block.terminator
                    else {
                        return Err(CodegenError::InvalidMir(
                            "selection header missing If terminator".to_string(),
                        ));
                    };
                    let cond_s = self.value_to_wgsl(cond, &func.locals, bindings)?;
                    self.writeln(&format!("if ({cond_s}) {{"));
                    self.indent += 1;
                    self.emit_region(
                        *then_block,
                        Some(merge),
                        blocks,
                        func,
                        cfg,
                        bindings,
                        visited,
                    )?;
                    self.indent -= 1;
                    if *else_block != merge && !Self::is_empty_goto(*else_block, merge, blocks) {
                        self.writeln("} else {");
                        self.indent += 1;
                        self.emit_region(
                            *else_block,
                            Some(merge),
                            blocks,
                            func,
                            cfg,
                            bindings,
                            visited,
                        )?;
                        self.indent -= 1;
                    }
                    self.writeln("}");
                    current = Some(merge);
                }
                None => {
                    self.emit_block_stmts(block, func, bindings)?;
                    current =
                        self.emit_plain_terminator(&block.terminator, func, bindings, stop_at)?;
                }
            }
        }
        Ok(())
    }

    fn emit_block_stmts(
        &mut self,
        block: &MirBlock,
        func: &MirFunction,
        bindings: &EntryBindings,
    ) -> CodegenResult<()> {
        for stmt in &block.stmts {
            match &stmt.kind {
                MirStmtKind::Assign { dest, value } => {
                    if bindings.workgroup_vars.contains_key(dest) {
                        continue;
                    }
                    let dest_ty = func.locals.iter().find(|l| l.id == *dest).map(|l| &l.ty);
                    if matches!(dest_ty, Some(MirType::Void)) {
                        continue;
                    }
                    let lhs = self.local_name(*dest, &func.locals);
                    let rhs = match value {
                        MirRValue::Use(v) => {
                            self.value_to_wgsl_typed(v, dest_ty, &func.locals, bindings)?
                        }
                        _ => self.rvalue_to_wgsl(value, func, bindings)?,
                    };
                    self.writeln(&format!("{lhs} = {rhs};"));
                }
                MirStmtKind::IndexStore {
                    base, index, value, ..
                } => {
                    let b = self.value_to_wgsl(base, &func.locals, bindings)?;
                    let idx_ty = Self::value_type(index, &func.locals);
                    let idx_expected = idx_ty
                        .as_ref()
                        .filter(|t| matches!(t, MirType::Int(IntSize::I32, _)))
                        .cloned()
                        .unwrap_or_else(MirType::u32);
                    let idx = self.value_to_wgsl_typed(
                        index,
                        Some(&idx_expected),
                        &func.locals,
                        bindings,
                    )?;
                    let val = self.rvalue_to_wgsl(value, func, bindings)?;
                    self.writeln(&format!("{b}[{idx}] = {val};"));
                }
                MirStmtKind::FieldAssign {
                    base,
                    field_name,
                    value,
                } => {
                    let b = self.local_name(*base, &func.locals);
                    let val = self.rvalue_to_wgsl(value, func, bindings)?;
                    self.writeln(&format!("{b}.{field_name} = {val};"));
                }
                MirStmtKind::WorkgroupBarrier => {
                    self.writeln("workgroupBarrier();");
                }
                MirStmtKind::StorageLive(_) | MirStmtKind::StorageDead(_) | MirStmtKind::Nop => {}
                MirStmtKind::GlobalStore { name, .. } => {
                    return Err(CodegenError::Unsupported(format!(
                        "mutable module global `{name}` store is not supported in WGSL"
                    )));
                }
                MirStmtKind::DerefAssign { .. } | MirStmtKind::FieldDerefAssign { .. } => {
                    return Err(CodegenError::Unsupported(
                        "raw pointer dereference assignment is not supported in WGSL".to_string(),
                    ));
                }
            }
        }
        Ok(())
    }

    fn emit_plain_terminator(
        &mut self,
        term: &Option<MirTerminator>,
        func: &MirFunction,
        bindings: &EntryBindings,
        stop_at: Option<BlockId>,
    ) -> CodegenResult<Option<BlockId>> {
        match term {
            None => Ok(None),
            Some(MirTerminator::Goto(target)) => {
                if stop_at == Some(*target) {
                    Ok(None)
                } else {
                    Ok(Some(*target))
                }
            }
            Some(MirTerminator::Return(Some(val))) => {
                if matches!(func.shader_stage, Some(ShaderStage::Compute)) {
                    self.writeln("return;");
                } else {
                    let v = self.value_to_wgsl(val, &func.locals, bindings)?;
                    self.writeln(&format!("return {v};"));
                }
                Ok(None)
            }
            Some(MirTerminator::Return(None)) => {
                self.writeln("return;");
                Ok(None)
            }
            Some(MirTerminator::Call {
                func: callee,
                args,
                dest,
                target,
                ..
            }) => {
                let expr = self.call_expr_to_wgsl(callee, args, &func.locals, bindings)?;
                if let Some(d) = dest {
                    let lhs = self.local_name(*d, &func.locals);
                    self.writeln(&format!("{lhs} = {expr};"));
                } else {
                    self.writeln(&format!("{expr};"));
                }
                Ok(target.filter(|t| stop_at != Some(*t)))
            }
            Some(MirTerminator::If { .. }) => Err(CodegenError::Unsupported(
                "unstructured control flow is not supported in WGSL".to_string(),
            )),
            Some(MirTerminator::Switch { .. }) => Err(CodegenError::Unsupported(
                "switch terminator is not yet supported in WGSL".to_string(),
            )),
            Some(MirTerminator::Unreachable) => {
                self.writeln("return;");
                Ok(None)
            }
            Some(MirTerminator::Drop { target, .. })
            | Some(MirTerminator::Assert { target, .. }) => Ok(Some(*target)),
            Some(MirTerminator::Resume | MirTerminator::Abort) => Err(CodegenError::Unsupported(
                "abort/unwind is not supported in WGSL shaders".to_string(),
            )),
        }
    }

    fn rvalue_to_wgsl(
        &self,
        rv: &MirRValue,
        func: &MirFunction,
        bindings: &EntryBindings,
    ) -> CodegenResult<String> {
        match rv {
            MirRValue::Use(v) => self.value_to_wgsl(v, &func.locals, bindings),
            MirRValue::BinaryOp { op, left, right } => {
                let l_ty = Self::value_type(left, &func.locals);
                let r_ty = Self::value_type(right, &func.locals);
                let l_expected = r_ty
                    .as_ref()
                    .filter(|t| matches!(t, MirType::Int(IntSize::I32, _)));
                let r_expected = l_ty
                    .as_ref()
                    .filter(|t| matches!(t, MirType::Int(IntSize::I32, _)));
                let l = self.value_to_wgsl_typed(left, l_expected, &func.locals, bindings)?;
                let r = self.value_to_wgsl_typed(right, r_expected, &func.locals, bindings)?;
                let sym = match op {
                    BinOp::Add | BinOp::AddChecked | BinOp::AddWrapping | BinOp::AddSaturating => {
                        "+"
                    }
                    BinOp::Sub | BinOp::SubChecked | BinOp::SubWrapping | BinOp::SubSaturating => {
                        "-"
                    }
                    BinOp::Mul | BinOp::MulChecked | BinOp::MulWrapping | BinOp::MulSaturating => {
                        "*"
                    }
                    BinOp::Div => "/",
                    BinOp::Rem => "%",
                    BinOp::Eq => "==",
                    BinOp::Ne => "!=",
                    BinOp::Lt => "<",
                    BinOp::Le => "<=",
                    BinOp::Gt => ">",
                    BinOp::Ge => ">=",
                    BinOp::BitAnd => "&",
                    BinOp::BitOr => "|",
                    BinOp::BitXor => "^",
                    BinOp::Shl => "<<",
                    BinOp::Shr => ">>",
                    BinOp::Pow => return Ok(format!("pow({l}, {r})")),
                };
                Ok(format!("({l} {sym} {r})"))
            }
            MirRValue::UnaryOp { op, operand } => {
                let v = self.value_to_wgsl(operand, &func.locals, bindings)?;
                Ok(match op {
                    UnaryOp::Neg => format!("(-{v})"),
                    UnaryOp::Not => format!("(!{v})"),
                    UnaryOp::BitNot => format!("(~{v})"),
                })
            }
            MirRValue::Cast { value, ty, .. } => {
                let v = self.value_to_wgsl(value, &func.locals, bindings)?;
                let t = self.type_to_wgsl(ty)?;
                Ok(format!("{t}({v})"))
            }
            MirRValue::FieldAccess {
                base, field_name, ..
            } => {
                let b = self.value_to_wgsl(base, &func.locals, bindings)?;
                Ok(format!("{b}.{field_name}"))
            }
            MirRValue::IndexAccess { base, index, .. } => {
                let b = self.value_to_wgsl(base, &func.locals, bindings)?;
                let idx_ty = Self::value_type(index, &func.locals);
                let idx_expected = idx_ty
                    .as_ref()
                    .filter(|t| matches!(t, MirType::Int(IntSize::I32, _)))
                    .cloned()
                    .unwrap_or_else(MirType::u32);
                let i =
                    self.value_to_wgsl_typed(index, Some(&idx_expected), &func.locals, bindings)?;
                Ok(format!("{b}[{i}]"))
            }
            MirRValue::Aggregate { kind, operands } => {
                let mut ops = Vec::with_capacity(operands.len());
                for o in operands {
                    ops.push(self.value_to_wgsl(o, &func.locals, bindings)?);
                }
                match kind {
                    AggregateKind::Struct(name) => {
                        let ctor = match name.as_ref() {
                            "build_vec2" => "vec2<f32>",
                            "build_vec3" => "vec3<f32>",
                            "build_vec4" => "vec4<f32>",
                            other => other,
                        };
                        Ok(format!("{ctor}({})", ops.join(", ")))
                    }
                    AggregateKind::Array(elem_ty) => {
                        let wty = self.type_to_wgsl(elem_ty)?;
                        Ok(format!("array<{wty}, {}>({})", ops.len(), ops.join(", ")))
                    }
                    _ => Err(CodegenError::Unsupported(format!(
                        "aggregate kind `{kind:?}` is not supported in WGSL"
                    ))),
                }
            }
            MirRValue::NullaryOp(op, _) => match op {
                NullaryOp::ThreadIndex(0) => Ok("_bl_gid.x".to_string()),
                NullaryOp::ThreadIndex(1) => Ok("_bl_gid.y".to_string()),
                NullaryOp::ThreadIndex(2) => Ok("_bl_gid.z".to_string()),
                NullaryOp::LocalInvocationId(0) => Ok("_bl_lid.x".to_string()),
                NullaryOp::LocalInvocationId(1) => Ok("_bl_lid.y".to_string()),
                NullaryOp::LocalInvocationId(2) => Ok("_bl_lid.z".to_string()),
                NullaryOp::WorkgroupId(0) => Ok("_bl_wid.x".to_string()),
                NullaryOp::WorkgroupId(1) => Ok("_bl_wid.y".to_string()),
                NullaryOp::WorkgroupId(2) => Ok("_bl_wid.z".to_string()),
                other => Err(CodegenError::Unsupported(format!(
                    "nullary op `{other:?}` is not supported in WGSL"
                ))),
            },
            MirRValue::TextureSample {
                texture,
                sampler,
                coords,
            } => {
                let t = self.value_to_wgsl(texture, &func.locals, bindings)?;
                let s = self.value_to_wgsl(sampler, &func.locals, bindings)?;
                let uv = self.value_to_wgsl(coords, &func.locals, bindings)?;
                Ok(format!("textureSample({t}, {s}, {uv})"))
            }
            other => Err(CodegenError::Unsupported(format!(
                "rvalue `{other:?}` is not supported in WGSL"
            ))),
        }
    }

    fn call_expr_to_wgsl(
        &self,
        callee: &MirValue,
        args: &[MirValue],
        locals: &[MirLocal],
        bindings: &EntryBindings,
    ) -> CodegenResult<String> {
        let name = match callee {
            MirValue::Function(n) | MirValue::Global(n) => n.as_ref(),
            _ => {
                return Err(CodegenError::Unsupported(
                    "indirect function calls are not supported in WGSL".to_string(),
                ));
            }
        };
        if matches!(
            name,
            "printf"
                | "puts"
                | "print"
                | "println"
                | "build_println_str"
                | "build_println_i64"
                | "build_println_f64"
                | "build_print_str"
        ) || name.starts_with("build_vec_")
            || name.starts_with("build_hmap_")
        {
            return Err(CodegenError::Unsupported(format!(
                "host runtime call `{name}` is not supported in WGSL shaders"
            )));
        }

        let mapped = match name {
            "fabs" | "fabsf" => "abs",
            "sqrtf" => "sqrt",
            "sinf" => "sin",
            "cosf" => "cos",
            "tanf" => "tan",
            "expf" => "exp",
            "logf" => "log",
            "powf" => "pow",
            "floorf" => "floor",
            "ceilf" => "ceil",
            "fmaf" => "fma",
            "build_dot2" | "build_dot3" | "build_dot4" => "dot",
            "build_normalize2" | "build_normalize3" | "build_normalize4" => "normalize",
            "build_length2" | "build_length3" | "build_length4" => "length",
            "build_cross" => "cross",
            "build_reflect3" => "reflect",
            "build_mix" | "lerp" | "build_lerp2" | "build_lerp3" | "build_lerp4" => "mix",
            "build_clampf" | "build_clamp3" => "clamp",
            "build_smoothstep" => "smoothstep",
            "build_fract" => "fract",
            "build_step" => "step",
            "build_min_f32" | "build_min_i32" => "min",
            "build_max_f32" | "build_max_i32" => "max",
            "build_vec2_new" => "vec2<f32>",
            "build_vec3_new" => "vec3<f32>",
            "build_vec4_new" => "vec4<f32>",
            other => other,
        };

        let mut arg_strs = Vec::with_capacity(args.len());
        for a in args {
            arg_strs.push(self.value_to_wgsl(a, locals, bindings)?);
        }
        Ok(format!("{mapped}({})", arg_strs.join(", ")))
    }

    fn value_to_wgsl(
        &self,
        value: &MirValue,
        locals: &[MirLocal],
        bindings: &EntryBindings,
    ) -> CodegenResult<String> {
        match value {
            MirValue::Local(id) => {
                if let Some(buf) = bindings.buffer_vars.get(id) {
                    return Ok(buf.clone());
                }
                if let Some(wg) = bindings.workgroup_vars.get(id) {
                    return Ok(wg.clone());
                }
                if let (Some(uvar), Some(field)) =
                    (&bindings.uniform_var, bindings.scalar_fields.get(id))
                {
                    return Ok(format!("{uvar}.{field}"));
                }
                Ok(self.local_name(*id, locals))
            }
            MirValue::Const(c) => self.const_to_wgsl(c),
            MirValue::Global(name) | MirValue::Function(name) => Ok(name.to_string()),
        }
    }

    fn value_type(value: &MirValue, locals: &[MirLocal]) -> Option<MirType> {
        match value {
            MirValue::Local(id) => locals.iter().find(|l| l.id == *id).map(|l| l.ty.clone()),
            _ => None,
        }
    }

    fn value_to_wgsl_typed(
        &self,
        value: &MirValue,
        expected: Option<&MirType>,
        locals: &[MirLocal],
        bindings: &EntryBindings,
    ) -> CodegenResult<String> {
        if let (MirValue::Const(MirConst::Int(v, _)), Some(MirType::Int(IntSize::I32, signed))) =
            (value, expected)
        {
            if !signed && *v >= 0 && u32::try_from(*v).is_ok() {
                return Ok(format!("{v}u"));
            }
            if *signed && i32::try_from(*v).is_ok() {
                return Ok(format!("{v}i"));
            }
        }
        self.value_to_wgsl(value, locals, bindings)
    }

    fn is_empty_goto(bid: BlockId, target: BlockId, blocks: &[MirBlock]) -> bool {
        blocks.iter().find(|b| b.id == bid).is_some_and(|b| {
            b.stmts.is_empty() && b.terminator == Some(MirTerminator::Goto(target))
        })
    }

    fn const_to_wgsl(&self, c: &MirConst) -> CodegenResult<String> {
        match c {
            MirConst::Bool(b) => Ok(if *b { "true" } else { "false" }.to_string()),
            MirConst::Int(v, ty) => match ty {
                MirType::Int(IntSize::I64 | IntSize::I128, _) => Err(CodegenError::Unsupported(
                    "64-bit/128-bit integer literal is not supported in WGSL; use i32 or u32"
                        .to_string(),
                )),
                MirType::Int(_, false) => Ok(format!("{v}u")),
                _ => Ok(format!("{v}i")),
            },
            MirConst::Uint(v, ty) => match ty {
                MirType::Int(IntSize::I64 | IntSize::I128, _) => Err(CodegenError::Unsupported(
                    "64-bit/128-bit unsigned integer literal is not supported in WGSL; use u32"
                        .to_string(),
                )),
                _ => Ok(format!("{v}u")),
            },
            MirConst::Float(v, ty) => {
                if matches!(ty, MirType::Float(FloatSize::F64)) {
                    return Err(CodegenError::Unsupported(
                        "f64 literal is not supported in WGSL; use f32".to_string(),
                    ));
                }
                let s = format!("{v}");
                if !s.contains('.') && !s.contains('e') && !s.contains('E') {
                    Ok(format!("{s}.0f"))
                } else {
                    Ok(format!("{s}f"))
                }
            }
            MirConst::Unit => Ok("0u".to_string()),
            MirConst::Str(_) | MirConst::ByteStr(_) => Err(CodegenError::Unsupported(
                "string constants are not supported in WGSL shaders".to_string(),
            )),
            other => Err(CodegenError::Unsupported(format!(
                "constant `{other:?}` is not supported in WGSL"
            ))),
        }
    }

    fn type_to_wgsl(&self, ty: &MirType) -> CodegenResult<String> {
        match ty {
            MirType::Void => Ok("void".to_string()),
            MirType::Bool => Ok("bool".to_string()),
            MirType::Int(size, signed) => match (size, signed) {
                (IntSize::I32, true) => Ok("i32".to_string()),
                (IntSize::I32, false) => Ok("u32".to_string()),
                _ => Err(CodegenError::Unsupported(format!(
                    "integer type `{ty}` is not supported in WGSL (only i32 and u32 are valid)"
                ))),
            },
            MirType::Float(FloatSize::F32) => Ok("f32".to_string()),
            MirType::Float(FloatSize::F64) => Err(CodegenError::Unsupported(
                "f64 type is not supported in WebGPU Shading Language (WGSL); use f32".to_string(),
            )),
            MirType::Struct(name) => Ok(match name.as_ref() {
                "build_vec2" => "vec2<f32>".to_string(),
                "build_vec3" => "vec3<f32>".to_string(),
                "build_vec4" => "vec4<f32>".to_string(),
                "build_mat4" => "mat4x4<f32>".to_string(),
                other => other.to_string(),
            }),
            MirType::Vector(elem, n) => Ok(format!("vec{n}<{}>", self.type_to_wgsl(elem)?)),
            MirType::Array(elem, len) => Ok(format!("array<{}, {len}>", self.type_to_wgsl(elem)?)),
            MirType::Texture2D(elem) => Ok(format!("texture_2d<{}>", self.type_to_wgsl(elem)?)),
            MirType::Sampler => Ok("sampler".to_string()),
            MirType::Vec(_) | MirType::Map(_, _) | MirType::TraitObject(_) | MirType::FnPtr(_) => {
                Err(CodegenError::Unsupported(format!(
                    "dynamic/host type `{ty}` is not supported in WGSL"
                )))
            }
            other => Err(CodegenError::Unsupported(format!(
                "type `{other}` is not supported in WGSL"
            ))),
        }
    }

    fn buffer_elem_type(ty: &MirType) -> Option<&MirType> {
        match ty {
            MirType::Slice(elem) => Some(elem.as_ref()),
            MirType::Ptr(inner) => match inner.as_ref() {
                MirType::Slice(elem) | MirType::Array(elem, _) => Some(elem.as_ref()),
                _ => None,
            },
            _ => None,
        }
    }

    fn workgroup_array_len(local: &MirLocal) -> Option<u32> {
        local
            .annotations
            .iter()
            .find_map(|a| a.strip_prefix("Workgroup:")?.parse::<u32>().ok())
    }

    fn find_written_buffer_params(func: &MirFunction) -> HashSet<LocalId> {
        let mut out = HashSet::new();
        if let Some(blocks) = &func.blocks {
            for b in blocks {
                for s in &b.stmts {
                    if let MirStmtKind::IndexStore {
                        base: MirValue::Local(id),
                        ..
                    } = &s.kind
                    {
                        out.insert(*id);
                    }
                }
            }
        }
        out
    }

    fn reads_nullary(func: &MirFunction, pred: impl Fn(&NullaryOp) -> bool) -> bool {
        func.blocks.as_ref().is_some_and(|blocks| {
            blocks.iter().any(|b| {
                b.stmts.iter().any(|s| match &s.kind {
                    MirStmtKind::Assign {
                        value: MirRValue::NullaryOp(op, _),
                        ..
                    } => pred(op),
                    _ => false,
                })
            })
        })
    }

    fn resolve_workgroup_size(func: &MirFunction) -> [u32; 3] {
        if let Some(sz) = func.workgroup_size {
            return sz;
        }
        if Self::reads_nullary(
            func,
            |op| matches!(op, NullaryOp::ThreadIndex(c) if *c >= 1),
        ) {
            [16, 16, 1]
        } else {
            [64, 1, 1]
        }
    }

    fn local_name(&self, id: LocalId, locals: &[MirLocal]) -> String {
        locals
            .iter()
            .find(|l| l.id == id)
            .and_then(|l| l.name.as_ref())
            .map(|n| match n.as_ref() {
                "var" | "let" | "fn" | "struct" | "uniform" | "storage" | "workgroup"
                | "private" | "function" | "return" | "loop" | "break" | "continue"
                | "override" | "const" | "alias" | "bitcast" | "discard" | "enable"
                | "requires" | "diagnostic" | "switch" | "case" | "default" | "for" | "while"
                | "if" | "else" | "true" | "false" | "f32" | "i32" | "u32" | "bool" | "array"
                | "vec2" | "vec3" | "vec4" | "mat4x4" | "ptr" | "atomic" => {
                    format!("_{n}")
                }
                other => other.to_string(),
            })
            .unwrap_or_else(|| format!("_{}", id.0))
    }
}

impl Default for WgslBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl Backend for WgslBackend {
    fn generate(&mut self, mir: &MirModule) -> CodegenResult<GeneratedCode> {
        let src = self.generate_source(mir)?;
        Ok(GeneratedCode::new(OutputFormat::Wgsl, src.into_bytes()))
    }

    fn target(&self) -> Target {
        Target::Wgsl
    }
}
