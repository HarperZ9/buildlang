//! 64-bit RISC-V (`RV64IMAFD` / `LP64D`) native assembly code generation backend.
//!
//! ## Calling Convention (LP64D)
//! - Integer arguments: `a0`..`a7`, return value in `a0`
//! - Floating-point arguments: `fa0`..`fa7`, return value in `fa0`
//! - Frame pointer: `s0` (`fp`), Link register: `ra`, Stack pointer: `sp` (16-byte aligned)
//! - Fail-closed refusal of unsupported GPU/heap constructs (never silent stub comments).

use std::fmt::Write;

use super::{Backend, CodegenError, CodegenResult, Target};
use crate::codegen::ir::*;
use crate::codegen::{GeneratedCode, OutputFormat};

/// 64-bit RISC-V (`RV64IMAFD` / `LP64D`) assembly backend.
pub struct Riscv64Backend {
    output: String,
    label_counter: u32,
    float_pool: Vec<(String, u64, bool)>, // (label, bits, is_f64)
}

impl Riscv64Backend {
    pub fn new() -> Self {
        Self {
            output: String::new(),
            label_counter: 0,
            float_pool: Vec::new(),
        }
    }

    fn generate_module(&mut self, module: &MirModule) -> CodegenResult<()> {
        self.output.clear();
        self.float_pool.clear();

        self.output.push_str("# Generated by BuildLang Compiler\n");
        self.output
            .push_str("# Target: RISC-V 64-bit (RV64IMAFD / LP64D)\n\n");
        self.output.push_str(".option arch, rv64imafd\n\n");

        // Pre-validate functions before emitting so refusals stay clean
        for func in &module.functions {
            if func.shader_stage.is_some() {
                return Err(CodegenError::Unsupported(format!(
                    "GPU shader function `{}` cannot be lowered to CPU target `riscv64`",
                    func.name
                )));
            }
        }

        self.output.push_str(".section .data\n");
        for global in &module.globals {
            if global.is_mut {
                self.emit_global(global)?;
            }
        }

        let mut text_buf = String::new();
        std::mem::swap(&mut self.output, &mut text_buf);
        self.output.push_str("\n.section .text\n");
        for func in &module.functions {
            if !func.is_declaration() {
                self.generate_function(func)?;
            }
        }
        std::mem::swap(&mut self.output, &mut text_buf);

        self.output.push_str("\n.section .rodata\n");
        for (i, s) in module.strings.iter().enumerate() {
            writeln!(self.output, "__str{i}:").unwrap();
            writeln!(self.output, "    .asciz \"{}\"", Self::escape_string(s)).unwrap();
        }
        for global in &module.globals {
            if !global.is_mut {
                self.emit_global(global)?;
            }
        }
        for (label, bits, is_f64) in &self.float_pool {
            if *is_f64 {
                self.output.push_str("    .align 3\n");
                writeln!(self.output, "{label}:").unwrap();
                writeln!(self.output, "    .quad 0x{bits:016x}").unwrap();
            } else {
                self.output.push_str("    .align 2\n");
                writeln!(self.output, "{label}:").unwrap();
                writeln!(self.output, "    .word 0x{:08x}", *bits as u32).unwrap();
            }
        }

        self.output.push_str(&text_buf);
        Ok(())
    }

    fn emit_global(&mut self, global: &MirGlobal) -> CodegenResult<()> {
        writeln!(self.output, ".globl {}", global.name).unwrap();
        writeln!(self.output, "{}:", global.name).unwrap();
        if let Some(init) = &global.init {
            self.emit_const_data(init, &global.ty)?;
        } else {
            writeln!(self.output, "    .zero {}", self.type_size(&global.ty)?).unwrap();
        }
        Ok(())
    }

    fn generate_function(&mut self, func: &MirFunction) -> CodegenResult<()> {
        for local in &func.locals {
            self.validate_type(&local.ty)?;
        }
        self.validate_type(&func.sig.ret)?;

        if func.is_public || func.name.as_ref() == "main" {
            writeln!(self.output, ".globl {}", func.name).unwrap();
        }
        writeln!(self.output, ".type {}, @function", func.name).unwrap();
        writeln!(self.output, "{}:", func.name).unwrap();

        let frame_size = self.frame_size(func)?;
        writeln!(self.output, "    addi sp, sp, -{frame_size}").unwrap();
        writeln!(self.output, "    sd ra, {}(sp)", frame_size - 8).unwrap();
        writeln!(self.output, "    sd s0, {}(sp)", frame_size - 16).unwrap();
        writeln!(self.output, "    addi s0, sp, {frame_size}").unwrap();

        self.store_arguments(func)?;

        if let Some(blocks) = &func.blocks {
            for block in blocks {
                self.generate_block(block, func, frame_size)?;
            }
        }

        writeln!(self.output, ".size {}, .-{}\n", func.name, func.name).unwrap();
        Ok(())
    }

    fn store_arguments(&mut self, func: &MirFunction) -> CodegenResult<()> {
        let int_regs = ["a0", "a1", "a2", "a3", "a4", "a5", "a6", "a7"];
        let flt_regs = ["fa0", "fa1", "fa2", "fa3", "fa4", "fa5", "fa6", "fa7"];
        let mut int_idx = 0usize;
        let mut flt_idx = 0usize;

        for local in func.locals.iter().filter(|l| l.is_param) {
            let off = self.local_offset(local.id, func)?;
            match local.ty {
                MirType::Float(FloatSize::F64) => {
                    if flt_idx >= flt_regs.len() {
                        return Err(CodegenError::Unsupported(
                            "more than 8 float parameters is not yet supported in riscv64"
                                .to_string(),
                        ));
                    }
                    writeln!(self.output, "    fsd {}, -{}(s0)", flt_regs[flt_idx], off).unwrap();
                    flt_idx += 1;
                }
                MirType::Float(FloatSize::F32) => {
                    if flt_idx >= flt_regs.len() {
                        return Err(CodegenError::Unsupported(
                            "more than 8 float parameters is not yet supported in riscv64"
                                .to_string(),
                        ));
                    }
                    writeln!(self.output, "    fsw {}, -{}(s0)", flt_regs[flt_idx], off).unwrap();
                    flt_idx += 1;
                }
                _ => {
                    if int_idx >= int_regs.len() {
                        return Err(CodegenError::Unsupported(
                            "more than 8 integer parameters is not yet supported in riscv64"
                                .to_string(),
                        ));
                    }
                    writeln!(self.output, "    sd {}, -{}(s0)", int_regs[int_idx], off).unwrap();
                    int_idx += 1;
                }
            }
        }
        Ok(())
    }

    fn generate_block(
        &mut self,
        block: &MirBlock,
        func: &MirFunction,
        frame_size: u32,
    ) -> CodegenResult<()> {
        writeln!(self.output, ".Lbb{}_{}:", func.name, block.id.0).unwrap();
        for stmt in &block.stmts {
            self.generate_statement(stmt, func)?;
        }
        if let Some(term) = &block.terminator {
            self.generate_terminator(term, func, frame_size)?;
        }
        Ok(())
    }

    fn generate_statement(&mut self, stmt: &MirStmt, func: &MirFunction) -> CodegenResult<()> {
        match &stmt.kind {
            MirStmtKind::Assign { dest, value } => self.generate_assign(*dest, value, func),
            MirStmtKind::StorageLive(_)
            | MirStmtKind::StorageDead(_)
            | MirStmtKind::WorkgroupBarrier
            | MirStmtKind::Nop => Ok(()),
            MirStmtKind::GlobalStore { name, .. } => Err(CodegenError::Unsupported(format!(
                "store to module global `{name}` is not yet supported in riscv64"
            ))),
            MirStmtKind::IndexStore { .. } => Err(CodegenError::Unsupported(
                "indexed store is not yet supported in riscv64".to_string(),
            )),
            MirStmtKind::DerefAssign { .. }
            | MirStmtKind::FieldDerefAssign { .. }
            | MirStmtKind::FieldAssign { .. } => Err(CodegenError::Unsupported(
                "aggregate/pointer field store is not yet supported in riscv64".to_string(),
            )),
        }
    }

    fn generate_assign(
        &mut self,
        dest: LocalId,
        value: &MirRValue,
        func: &MirFunction,
    ) -> CodegenResult<()> {
        let dest_ty = self.local_type(dest, func);
        if matches!(dest_ty, MirType::Void) {
            return Ok(());
        }
        match value {
            MirRValue::Use(v) => {
                if let MirType::Float(fs) = dest_ty {
                    self.load_float_to_reg(v, "ft0", fs, func)?;
                    self.store_float_local("ft0", dest, fs, func)?;
                } else {
                    self.load_int_to_reg(v, "t0", func)?;
                    self.store_int_local("t0", dest, func)?;
                }
            }
            MirRValue::BinaryOp { op, left, right } => {
                let lhs_ty = self.value_type(left, func);
                if let MirType::Float(fs) = lhs_ty {
                    self.load_float_to_reg(left, "ft0", fs, func)?;
                    self.load_float_to_reg(right, "ft1", fs, func)?;
                    self.emit_float_binop(*op, fs, dest, func)?;
                } else {
                    self.load_int_to_reg(left, "t0", func)?;
                    self.load_int_to_reg(right, "t1", func)?;
                    self.emit_int_binop(*op)?;
                    self.store_int_local("t0", dest, func)?;
                }
            }
            MirRValue::UnaryOp { op, operand } => {
                let op_ty = self.value_type(operand, func);
                if let MirType::Float(fs) = op_ty {
                    self.load_float_to_reg(operand, "ft0", fs, func)?;
                    match op {
                        UnaryOp::Neg => {
                            let sfx = if fs == FloatSize::F64 { "d" } else { "s" };
                            writeln!(self.output, "    fneg.{sfx} ft0, ft0").unwrap();
                            self.store_float_local("ft0", dest, fs, func)?;
                        }
                        _ => {
                            return Err(CodegenError::Unsupported(format!(
                                "unary op `{op:?}` on float is not supported in riscv64"
                            )));
                        }
                    }
                } else {
                    self.load_int_to_reg(operand, "t0", func)?;
                    match op {
                        UnaryOp::Neg => self.output.push_str("    neg t0, t0\n"),
                        UnaryOp::Not => self.output.push_str("    seqz t0, t0\n"),
                        UnaryOp::BitNot => self.output.push_str("    not t0, t0\n"),
                    }
                    self.store_int_local("t0", dest, func)?;
                }
            }
            MirRValue::Cast { value, ty, .. } => {
                let src_ty = self.value_type(value, func);
                match (&src_ty, ty) {
                    (MirType::Int(_, _), MirType::Int(_, _))
                    | (MirType::Bool, MirType::Int(_, _)) => {
                        self.load_int_to_reg(value, "t0", func)?;
                        self.store_int_local("t0", dest, func)?;
                    }
                    (MirType::Int(_, signed), MirType::Float(fs)) => {
                        self.load_int_to_reg(value, "t0", func)?;
                        let f_sfx = if *fs == FloatSize::F64 { "d" } else { "s" };
                        let i_sfx = if *signed { "l" } else { "lu" };
                        writeln!(self.output, "    fcvt.{f_sfx}.{i_sfx} ft0, t0").unwrap();
                        self.store_float_local("ft0", dest, *fs, func)?;
                    }
                    (MirType::Float(fs), MirType::Int(_, signed)) => {
                        self.load_float_to_reg(value, "ft0", *fs, func)?;
                        let f_sfx = if *fs == FloatSize::F64 { "d" } else { "s" };
                        let i_sfx = if *signed { "l" } else { "lu" };
                        writeln!(self.output, "    fcvt.{i_sfx}.{f_sfx} t0, ft0, rtz").unwrap();
                        self.store_int_local("t0", dest, func)?;
                    }
                    (MirType::Float(FloatSize::F32), MirType::Float(FloatSize::F64)) => {
                        self.load_float_to_reg(value, "ft0", FloatSize::F32, func)?;
                        self.output.push_str("    fcvt.d.s ft0, ft0\n");
                        self.store_float_local("ft0", dest, FloatSize::F64, func)?;
                    }
                    (MirType::Float(FloatSize::F64), MirType::Float(FloatSize::F32)) => {
                        self.load_float_to_reg(value, "ft0", FloatSize::F64, func)?;
                        self.output.push_str("    fcvt.s.d ft0, ft0\n");
                        self.store_float_local("ft0", dest, FloatSize::F32, func)?;
                    }
                    _ => {
                        return Err(CodegenError::Unsupported(format!(
                            "cast `{src_ty}` -> `{ty}` is not supported in riscv64"
                        )));
                    }
                }
            }
            MirRValue::NullaryOp(NullaryOp::SizeOf, ty) => {
                let sz = self.type_size(ty)?;
                writeln!(self.output, "    li t0, {sz}").unwrap();
                self.store_int_local("t0", dest, func)?;
            }
            MirRValue::NullaryOp(NullaryOp::AlignOf, ty) => {
                let al = self.type_size(ty)?.min(8).max(1);
                writeln!(self.output, "    li t0, {al}").unwrap();
                self.store_int_local("t0", dest, func)?;
            }
            other => {
                return Err(CodegenError::Unsupported(format!(
                    "rvalue `{other:?}` is not supported in riscv64"
                )));
            }
        }
        Ok(())
    }

    fn emit_int_binop(&mut self, op: BinOp) -> CodegenResult<()> {
        match op {
            BinOp::Add | BinOp::AddChecked | BinOp::AddWrapping | BinOp::AddSaturating => {
                self.output.push_str("    add t0, t0, t1\n");
            }
            BinOp::Sub | BinOp::SubChecked | BinOp::SubWrapping | BinOp::SubSaturating => {
                self.output.push_str("    sub t0, t0, t1\n");
            }
            BinOp::Mul | BinOp::MulChecked | BinOp::MulWrapping | BinOp::MulSaturating => {
                self.output.push_str("    mul t0, t0, t1\n");
            }
            BinOp::Div => self.output.push_str("    div t0, t0, t1\n"),
            BinOp::Rem => self.output.push_str("    rem t0, t0, t1\n"),
            BinOp::BitAnd => self.output.push_str("    and t0, t0, t1\n"),
            BinOp::BitOr => self.output.push_str("    or t0, t0, t1\n"),
            BinOp::BitXor => self.output.push_str("    xor t0, t0, t1\n"),
            BinOp::Shl => self.output.push_str("    sll t0, t0, t1\n"),
            BinOp::Shr => self.output.push_str("    sra t0, t0, t1\n"),
            BinOp::Eq => {
                self.output.push_str("    sub t0, t0, t1\n");
                self.output.push_str("    seqz t0, t0\n");
            }
            BinOp::Ne => {
                self.output.push_str("    sub t0, t0, t1\n");
                self.output.push_str("    snez t0, t0\n");
            }
            BinOp::Lt => self.output.push_str("    slt t0, t0, t1\n"),
            BinOp::Le => {
                self.output.push_str("    slt t0, t1, t0\n");
                self.output.push_str("    xori t0, t0, 1\n");
            }
            BinOp::Gt => self.output.push_str("    slt t0, t1, t0\n"),
            BinOp::Ge => {
                self.output.push_str("    slt t0, t0, t1\n");
                self.output.push_str("    xori t0, t0, 1\n");
            }
            BinOp::Pow => {
                let id = self.label_counter;
                self.label_counter += 1;
                self.output.push_str("    li t2, 1\n");
                writeln!(self.output, ".Lrv_pow_loop_{id}:").unwrap();
                writeln!(self.output, "    beqz t1, .Lrv_pow_done_{id}").unwrap();
                self.output.push_str("    andi t3, t1, 1\n");
                writeln!(self.output, "    beqz t3, .Lrv_pow_skip_{id}").unwrap();
                self.output.push_str("    mul t2, t2, t0\n");
                writeln!(self.output, ".Lrv_pow_skip_{id}:").unwrap();
                self.output.push_str("    mul t0, t0, t0\n");
                self.output.push_str("    srli t1, t1, 1\n");
                writeln!(self.output, "    j .Lrv_pow_loop_{id}").unwrap();
                writeln!(self.output, ".Lrv_pow_done_{id}:").unwrap();
                self.output.push_str("    mv t0, t2\n");
            }
        }
        Ok(())
    }

    fn emit_float_binop(
        &mut self,
        op: BinOp,
        fs: FloatSize,
        dest: LocalId,
        func: &MirFunction,
    ) -> CodegenResult<()> {
        let sfx = if fs == FloatSize::F64 { "d" } else { "s" };
        match op {
            BinOp::Add => {
                writeln!(self.output, "    fadd.{sfx} ft0, ft0, ft1").unwrap();
                self.store_float_local("ft0", dest, fs, func)
            }
            BinOp::Sub => {
                writeln!(self.output, "    fsub.{sfx} ft0, ft0, ft1").unwrap();
                self.store_float_local("ft0", dest, fs, func)
            }
            BinOp::Mul => {
                writeln!(self.output, "    fmul.{sfx} ft0, ft0, ft1").unwrap();
                self.store_float_local("ft0", dest, fs, func)
            }
            BinOp::Div => {
                writeln!(self.output, "    fdiv.{sfx} ft0, ft0, ft1").unwrap();
                self.store_float_local("ft0", dest, fs, func)
            }
            BinOp::Eq => {
                writeln!(self.output, "    feq.{sfx} t0, ft0, ft1").unwrap();
                self.store_int_local("t0", dest, func)
            }
            BinOp::Ne => {
                writeln!(self.output, "    feq.{sfx} t0, ft0, ft1").unwrap();
                self.output.push_str("    xori t0, t0, 1\n");
                self.store_int_local("t0", dest, func)
            }
            BinOp::Lt => {
                writeln!(self.output, "    flt.{sfx} t0, ft0, ft1").unwrap();
                self.store_int_local("t0", dest, func)
            }
            BinOp::Le => {
                writeln!(self.output, "    fle.{sfx} t0, ft0, ft1").unwrap();
                self.store_int_local("t0", dest, func)
            }
            BinOp::Gt => {
                writeln!(self.output, "    flt.{sfx} t0, ft1, ft0").unwrap();
                self.store_int_local("t0", dest, func)
            }
            BinOp::Ge => {
                writeln!(self.output, "    fle.{sfx} t0, ft1, ft0").unwrap();
                self.store_int_local("t0", dest, func)
            }
            other => Err(CodegenError::Unsupported(format!(
                "floating-point binary op `{other:?}` is not supported in riscv64"
            ))),
        }
    }

    fn generate_terminator(
        &mut self,
        term: &MirTerminator,
        func: &MirFunction,
        frame_size: u32,
    ) -> CodegenResult<()> {
        match term {
            MirTerminator::Goto(target) => {
                writeln!(self.output, "    j .Lbb{}_{}", func.name, target.0).unwrap();
            }
            MirTerminator::If {
                cond,
                then_block,
                else_block,
            } => {
                self.load_int_to_reg(cond, "t0", func)?;
                writeln!(
                    self.output,
                    "    bnez t0, .Lbb{}_{}",
                    func.name, then_block.0
                )
                .unwrap();
                writeln!(self.output, "    j .Lbb{}_{}", func.name, else_block.0).unwrap();
            }
            MirTerminator::Switch {
                value,
                targets,
                default,
            } => {
                self.load_int_to_reg(value, "t0", func)?;
                for (c, bid) in targets {
                    let imm = match c {
                        MirConst::Int(v, _) => *v as i64,
                        MirConst::Uint(v, _) => *v as i64,
                        MirConst::Bool(b) => i64::from(*b),
                        _ => {
                            return Err(CodegenError::Unsupported(
                                "non-integer switch constant in riscv64".to_string(),
                            ));
                        }
                    };
                    writeln!(self.output, "    li t1, {imm}").unwrap();
                    writeln!(self.output, "    beq t0, t1, .Lbb{}_{}", func.name, bid.0).unwrap();
                }
                writeln!(self.output, "    j .Lbb{}_{}", func.name, default.0).unwrap();
            }
            MirTerminator::Return(val) => {
                if let Some(v) = val {
                    if let MirType::Float(fs) = func.sig.ret {
                        self.load_float_to_reg(v, "fa0", fs, func)?;
                    } else if !matches!(func.sig.ret, MirType::Void) {
                        self.load_int_to_reg(v, "a0", func)?;
                    }
                }
                writeln!(self.output, "    ld ra, {}(sp)", frame_size - 8).unwrap();
                writeln!(self.output, "    ld s0, {}(sp)", frame_size - 16).unwrap();
                writeln!(self.output, "    addi sp, sp, {frame_size}").unwrap();
                self.output.push_str("    ret\n");
            }
            MirTerminator::Call {
                func: callee,
                args,
                dest,
                target,
                ..
            } => {
                let callee_name = match callee {
                    MirValue::Function(name) | MirValue::Global(name) => name.to_string(),
                    _ => {
                        return Err(CodegenError::Unsupported(
                            "indirect call is not supported in riscv64".to_string(),
                        ));
                    }
                };
                let int_regs = ["a0", "a1", "a2", "a3", "a4", "a5", "a6", "a7"];
                let flt_regs = ["fa0", "fa1", "fa2", "fa3", "fa4", "fa5", "fa6", "fa7"];
                let mut int_idx = 0usize;
                let mut flt_idx = 0usize;
                for arg in args {
                    let arg_ty = self.value_type(arg, func);
                    if let MirType::Float(fs) = arg_ty {
                        if flt_idx >= flt_regs.len() {
                            return Err(CodegenError::Unsupported(
                                "call with > 8 float arguments is not yet supported in riscv64"
                                    .to_string(),
                            ));
                        }
                        self.load_float_to_reg(arg, flt_regs[flt_idx], fs, func)?;
                        flt_idx += 1;
                    } else {
                        if int_idx >= int_regs.len() {
                            return Err(CodegenError::Unsupported(
                                "call with > 8 integer arguments is not yet supported in riscv64"
                                    .to_string(),
                            ));
                        }
                        self.load_int_to_reg(arg, int_regs[int_idx], func)?;
                        int_idx += 1;
                    }
                }
                writeln!(self.output, "    call {callee_name}").unwrap();
                if let Some(d) = dest {
                    let dty = self.local_type(*d, func);
                    if let MirType::Float(fs) = dty {
                        self.store_float_local("fa0", *d, fs, func)?;
                    } else if !matches!(dty, MirType::Void) {
                        self.store_int_local("a0", *d, func)?;
                    }
                }
                if let Some(tb) = target {
                    writeln!(self.output, "    j .Lbb{}_{}", func.name, tb.0).unwrap();
                }
            }
            MirTerminator::Unreachable => self.output.push_str("    ebreak\n"),
            MirTerminator::Abort => self.output.push_str("    call abort\n"),
            MirTerminator::Drop { target, .. } | MirTerminator::Assert { target, .. } => {
                writeln!(self.output, "    j .Lbb{}_{}", func.name, target.0).unwrap();
            }
            MirTerminator::Resume => {
                return Err(CodegenError::Unsupported(
                    "unwind resume is not supported in riscv64".to_string(),
                ));
            }
        }
        Ok(())
    }

    fn load_int_to_reg(
        &mut self,
        val: &MirValue,
        reg: &str,
        func: &MirFunction,
    ) -> CodegenResult<()> {
        match val {
            MirValue::Local(id) => {
                let off = self.local_offset(*id, func)?;
                writeln!(self.output, "    ld {reg}, -{off}(s0)").unwrap();
            }
            MirValue::Const(c) => match c {
                MirConst::Int(v, _) => {
                    writeln!(self.output, "    li {reg}, {}", *v as i64).unwrap()
                }
                MirConst::Uint(v, _) => {
                    writeln!(self.output, "    li {reg}, {}", *v as i64).unwrap()
                }
                MirConst::Bool(b) => {
                    writeln!(self.output, "    li {reg}, {}", if *b { 1 } else { 0 }).unwrap()
                }
                MirConst::Str(idx) => writeln!(self.output, "    la {reg}, __str{idx}").unwrap(),
                MirConst::Unit | MirConst::Null(_) => {
                    writeln!(self.output, "    li {reg}, 0").unwrap()
                }
                other => {
                    return Err(CodegenError::Unsupported(format!(
                        "constant `{other:?}` cannot be loaded into integer register in riscv64"
                    )));
                }
            },
            MirValue::Global(name) | MirValue::Function(name) => {
                writeln!(self.output, "    la {reg}, {name}").unwrap();
            }
        }
        Ok(())
    }

    fn load_float_to_reg(
        &mut self,
        val: &MirValue,
        freg: &str,
        fs: FloatSize,
        func: &MirFunction,
    ) -> CodegenResult<()> {
        let is_f64 = fs == FloatSize::F64;
        let load_op = if is_f64 { "fld" } else { "flw" };
        match val {
            MirValue::Local(id) => {
                let off = self.local_offset(*id, func)?;
                writeln!(self.output, "    {load_op} {freg}, -{off}(s0)").unwrap();
            }
            MirValue::Const(MirConst::Float(v, _)) => {
                let label = format!(".Lrv_flt_{}", self.label_counter);
                self.label_counter += 1;
                let bits = if is_f64 {
                    v.to_bits()
                } else {
                    (*v as f32).to_bits() as u64
                };
                self.float_pool.push((label.clone(), bits, is_f64));
                writeln!(self.output, "    la t6, {label}").unwrap();
                writeln!(self.output, "    {load_op} {freg}, 0(t6)").unwrap();
            }
            other => {
                return Err(CodegenError::Unsupported(format!(
                    "float value `{other:?}` cannot be loaded in riscv64"
                )));
            }
        }
        Ok(())
    }

    fn store_int_local(&mut self, reg: &str, id: LocalId, func: &MirFunction) -> CodegenResult<()> {
        let off = self.local_offset(id, func)?;
        writeln!(self.output, "    sd {reg}, -{off}(s0)").unwrap();
        Ok(())
    }

    fn store_float_local(
        &mut self,
        freg: &str,
        id: LocalId,
        fs: FloatSize,
        func: &MirFunction,
    ) -> CodegenResult<()> {
        let off = self.local_offset(id, func)?;
        let op = if fs == FloatSize::F64 { "fsd" } else { "fsw" };
        writeln!(self.output, "    {op} {freg}, -{off}(s0)").unwrap();
        Ok(())
    }

    fn emit_const_data(&mut self, c: &MirConst, ty: &MirType) -> CodegenResult<()> {
        match c {
            MirConst::Int(v, _) => writeln!(self.output, "    .quad {}", *v as i64).unwrap(),
            MirConst::Uint(v, _) => writeln!(self.output, "    .quad {}", *v as u64).unwrap(),
            MirConst::Float(v, fty) => match fty {
                MirType::Float(FloatSize::F32) => {
                    writeln!(self.output, "    .word 0x{:08x}", (*v as f32).to_bits()).unwrap();
                }
                _ => writeln!(self.output, "    .quad 0x{:016x}", v.to_bits()).unwrap(),
            },
            MirConst::Bool(b) => writeln!(self.output, "    .byte {}", u8::from(*b)).unwrap(),
            _ => writeln!(self.output, "    .zero {}", self.type_size(ty)?).unwrap(),
        }
        Ok(())
    }

    fn frame_size(&self, func: &MirFunction) -> CodegenResult<u32> {
        // Reserve 16 bytes for saved ra + s0, plus 8 bytes per local slot, 16-byte aligned.
        let locals_bytes = (func.locals.len() as u32) * 8;
        let total = 16 + locals_bytes;
        Ok((total + 15) & !15)
    }

    fn local_offset(&self, id: LocalId, func: &MirFunction) -> CodegenResult<u32> {
        let idx = func
            .locals
            .iter()
            .position(|l| l.id == id)
            .ok_or_else(|| CodegenError::InvalidMir(format!("unknown local {id}")))?;
        // Saved ra at -8(s0), saved s0 at -16(s0), locals start at -24(s0).
        Ok(24 + (idx as u32) * 8)
    }

    fn local_type(&self, id: LocalId, func: &MirFunction) -> MirType {
        func.locals
            .iter()
            .find(|l| l.id == id)
            .map(|l| l.ty.clone())
            .unwrap_or(MirType::Void)
    }

    fn value_type(&self, val: &MirValue, func: &MirFunction) -> MirType {
        match val {
            MirValue::Local(id) => self.local_type(*id, func),
            MirValue::Const(c) => match c {
                MirConst::Bool(_) => MirType::Bool,
                MirConst::Int(_, ty) | MirConst::Uint(_, ty) | MirConst::Float(_, ty) => ty.clone(),
                MirConst::Str(_) => MirType::Ptr(Box::new(MirType::Int(IntSize::I8, false))),
                _ => MirType::Int(IntSize::I64, true),
            },
            MirValue::Global(_) | MirValue::Function(_) => MirType::Ptr(Box::new(MirType::Void)),
        }
    }

    fn validate_type(&self, ty: &MirType) -> CodegenResult<()> {
        match ty {
            MirType::Vec(_)
            | MirType::Map(_, _)
            | MirType::TraitObject(_)
            | MirType::Texture2D(_)
            | MirType::Sampler
            | MirType::SampledImage(_) => Err(CodegenError::Unsupported(format!(
                "type `{ty}` is not supported in riscv64 backend"
            ))),
            _ => Ok(()),
        }
    }

    fn type_size(&self, ty: &MirType) -> CodegenResult<usize> {
        self.validate_type(ty)?;
        Ok(match ty {
            MirType::Void => 0,
            MirType::Bool => 1,
            MirType::Int(IntSize::I8, _) => 1,
            MirType::Int(IntSize::I16, _) => 2,
            MirType::Int(IntSize::I32, _) => 4,
            MirType::Int(IntSize::I64 | IntSize::ISize, _) => 8,
            MirType::Int(IntSize::I128, _) => 16,
            MirType::Float(FloatSize::F32) => 4,
            MirType::Float(FloatSize::F64) => 8,
            MirType::Ptr(_) | MirType::FnPtr(_) => 8,
            MirType::Slice(_) => 16,
            MirType::Array(elem, len) => self.type_size(elem)? * (*len as usize),
            _ => 8,
        })
    }

    fn escape_string(s: &str) -> String {
        let mut out = String::with_capacity(s.len());
        for c in s.chars() {
            match c {
                '\n' => out.push_str("\\n"),
                '\r' => out.push_str("\\r"),
                '\t' => out.push_str("\\t"),
                '\\' => out.push_str("\\\\"),
                '"' => out.push_str("\\\""),
                other => out.push(other),
            }
        }
        out
    }
}

impl Default for Riscv64Backend {
    fn default() -> Self {
        Self::new()
    }
}

impl Backend for Riscv64Backend {
    fn generate(&mut self, mir: &MirModule) -> CodegenResult<GeneratedCode> {
        self.generate_module(mir)?;
        Ok(GeneratedCode::new(
            OutputFormat::Assembly,
            self.output.clone().into_bytes(),
        ))
    }

    fn target(&self) -> Target {
        Target::Riscv64
    }
}
